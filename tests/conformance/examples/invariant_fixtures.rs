//! Refresh explicit fixtures when a reviewed registry invariant changes.
#[path = "../src/fixture.rs"]
mod fixture;
use std::{fmt::Write as _, io::Write as _};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    let registry = pse_schema::catalog::assemble()?;
    let cases = registry
        .invariants()
        .iter()
        .map(|invariant| {
            (
                fixture::directory(invariant),
                fixture::pair(&registry, invariant),
            )
        })
        .collect::<Vec<_>>();
    let paths = cases
        .iter()
        .map(|(path, _)| path.clone())
        .collect::<std::collections::BTreeSet<_>>();
    let mut tests = String::from(
        "// SPDX-License-Identifier: MIT OR Apache-2.0\n// Copyright (c) 2026 Paul Heyse\n// @generated by invariant_fixtures; do not edit\n\n",
    );
    let mut names = std::collections::BTreeSet::new();
    let mut mismatches = Vec::new();
    for (path, (valid, violating)) in cases {
        for (case, value) in [("valid", valid), ("violating", violating)] {
            let text = format!("{}\n", serde_json::to_string_pretty(&value)?);
            emit(
                &path.join(format!("{case}.yaml")),
                &text,
                check,
                &mut mismatches,
            )?;
            let name = format!("{}_{}", value.invariant.replace([':', '.', '-'], "_"), case);
            if !names.insert(name.clone()) {
                return Err(format!("duplicate invariant test identity: {name}").into());
            }
            write!(
                tests,
                "#[tokio::test]\nasync fn {name}() {{\n    super::assert_fixture({:?}, {case:?}).await;\n}}\n\n",
                value.invariant
            )?;
        }
    }
    let generated =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/generated/invariant_cases.rs");
    // Use the pinned formatter exactly as ordinary generated Rust sources do.
    let mut formatter = std::process::Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()?;
    formatter
        .stdin
        .take()
        .ok_or("rustfmt stdin absent")?
        .write_all(tests.as_bytes())?;
    let result = formatter.wait_with_output()?;
    if !result.status.success() {
        return Err("invariant test rustfmt failed".into());
    }
    emit(
        &generated,
        &String::from_utf8(result.stdout)?,
        check,
        &mut mismatches,
    )?;
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures/invariants");
    for entry in std::fs::read_dir(root)? {
        let entry = entry?;
        if entry.file_type()?.is_dir() && !paths.contains(&entry.path()) {
            if check {
                mismatches.push(entry.path());
            } else {
                std::fs::remove_dir_all(entry.path())?;
            }
        }
    }
    if !mismatches.is_empty() {
        return Err(format!("stale generated invariant fixtures: {mismatches:?}").into());
    }
    Ok(())
}

fn emit(
    path: &std::path::Path,
    text: &str,
    check: bool,
    mismatches: &mut Vec<std::path::PathBuf>,
) -> std::io::Result<()> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return Ok(());
    }
    if check {
        mismatches.push(path.to_owned());
    } else {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, text)?;
    }
    Ok(())
}
