fn native_abi(_: &Path, _: bool) -> Result<()> {
    bail!("native bindings require native-abi and the actual selected headers")
}

/// Published source-bearing native JSON Schemas, derived from the owning
/// crates' serde types (ADR-0116 Outcome 7).
#[cfg(feature = "product-schemas")]
fn document_schemas(registry: &pse_schema::Registry) -> Result<GeneratedTree> {
    let mut tree = documents::generate_catalogue(
        registry,
        &schemas::documents(),
        pse_runtime::boundary_documents::fingerprint()?,
    )?;
    let mut private = documents::generate_private(
        registry,
        &[documents::Document {
            name: "telemetry-settings".into(),
            schema: schemars::schema_for!(pse_runtime::tooling::telemetry::Settings).to_value(),
        }],
    )?;
    let evidence = documents::generate_private_catalogue(&private_documents::documents())?;
    private.roots.extend(evidence.roots);
    private.files.extend(evidence.files);
    private.relationships.extend(evidence.relationships);
    let deployment_document = |name: &str, title: &str, mut schema: serde_json::Value| {
        schema["title"] = title.into();
        documents::Document {
            name: name.into(),
            schema,
        }
    };
    let deployment = documents::generate_private_family(registry, "deployment", &[
        deployment_document("deployment-request", "DeploymentRequest", schemars::schema_for!(pse_runtime::boundary_documents::Versioned<pse_runtime::workflow::DeploymentRequest, 1>).to_value()),
        deployment_document("deployment-response", "DeploymentResponse", schemars::schema_for!(pse_runtime::boundary_documents::Versioned<pse_runtime::workflow::DeploymentResponse, 1>).to_value()),
        deployment_document("production-profiles", "ProductionProfiles", schemars::schema_for!(pse_runtime::workflow::ProductionProfiles).to_value()),
        deployment_document("registered-native-context", "RegisteredNativeContext", schemars::schema_for!(pse_runtime::workflow::RegisteredNativeContext).to_value()),
        deployment_document("deployment-observation", "DeploymentObservation", schemars::schema_for!(pse_runtime::boundary_documents::Versioned<pse_runtime::workflow::DeploymentObservation, 1>).to_value()),
        deployment_document("service-identity", "ServiceIdentity", schemars::schema_for!(pse_operations::deployment::ServiceIdentity).to_value()),
        deployment_document("canonical-connection-settings", "CanonicalConnectionSettings", schemars::schema_for!(pse_operations::deployment::CanonicalConnectionSettings).to_value()),
        deployment_document("managed-execution-policy", "ManagedExecutionPolicy", schemars::schema_for!(pse_runtime::workflow::ManagedExecutionPolicy).to_value()),
        deployment_document("canonical-initialization-report", "CanonicalInitializationReport", schemars::schema_for!(pse_operations::deployment::CanonicalInitializationReport).to_value()),
        deployment_document("recovery-checkpoint", "RecoveryCheckpoint", schemars::schema_for!(pse_operations::canonical_files::offline::RecoveryCheckpoint).to_value()),
        deployment_document("backup-operation", "BackupOperation", schemars::schema_for!(pse_operations::deployment::BackupOperation).to_value()),
        deployment_document("prepared-receiver-environment", "PreparedReceiverEnvironment", schemars::schema_for!(pse_runtime::workflow::PreparedReceiverEnvironment).to_value()),
    ])?;
    private.roots.extend(deployment.roots);
    private.files.extend(deployment.files);
    private.relationships.extend(deployment.relationships);
    let metric_path =
        Path::new(documents::PRIVATE_SCHEMA_ROOT).join("native_metric_declarations.json");
    private.roots.push(metric_path.clone());
    private.files.insert(
        metric_path.clone(),
        serde_json::to_vec_pretty(
            pse_runtime::tooling::metric_declarations::metric_declarations(),
        )?,
    );
    tree.roots.extend(private.roots);
    tree.files.extend(private.files);
    tree.relationships.extend(private.relationships);
    tree.relationships.push(provenance::SourceRelationship {
        declaration_key: "pse_runtime::tooling::telemetry::Settings".into(),
        declaration_kind: "private_bootstrap_contract".into(),
        source_path: Some("crates/pse-runtime/src/tooling/telemetry.rs".into()),
        source_symbol: Some("Settings".into()),
        source_role: "definition".into(),
        source_identity: None,
        generator_path: "crates/pse-codegen/src/codegen/documents.rs".into(),
        generator_symbol: "generate_private".into(),
        output_path: format!("{}/telemetry-settings.schema.json", documents::PRIVATE_SCHEMA_ROOT),
        direction: Some("input".into()),
        contract_sections: Vec::new(),
        basis: "declared".into(),
    });
    tree.relationships.push(provenance::SourceRelationship {
        declaration_key: "pse_runtime::tooling::metric_declarations".into(),
        declaration_kind: "native_metric_declarations".into(),
        source_path: Some("crates/pse-runtime/src/tooling/metric_declarations.rs".into()),
        source_symbol: Some("metric_declarations".into()),
        source_role: "definition".into(),
        source_identity: None,
        generator_path: "xtask/src/codegen.rs".into(),
        generator_symbol: "document_schemas".into(),
        output_path: metric_path.to_string_lossy().into_owned(),
        direction: Some("output".into()),
        contract_sections: Vec::new(),
        basis: "declared".into(),
    });
    Ok(tree)
}

