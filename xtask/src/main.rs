/// The gate `governance / *` runs: the governance test crate, then the two checks that
/// need a resolved graph or git.
fn governance(root: &Path) -> Result<()> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    // `cargo -C <path>` is nightly-only; the working directory is the portable form.
    let status = Command::new(cargo)
        .args([
            "nextest",
            "run",
            "-p",
            "pse-tests-governance",
            "-p",
            "pse-relations",
            "--features",
            "pse-relations/force-validate",
            "--no-fail-fast",
            "--locked",
        ])
        .current_dir(root)
        .status()
        .context("running cargo nextest for pse-tests-governance")?;
    let generated = codegen(root, true, None);
    let families = family_check(root, &default_evidence(), true);
    ensure!(
        status.success() && generated.is_ok() && families.is_ok(),
        "governance tests: {status}; generation: {generated:?}; families: {families:?}"
    );
    Ok(())
}

