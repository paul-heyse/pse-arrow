#[derive(Debug, Subcommand)]
enum Cmd {
    /// Initialize a clean canonical database through its generated declaration route.
    #[cfg(feature = "canonical-tools")]
    CanonicalInit {
        state: PathBuf,
    },
    /// Derive a relevant producer identity from selected Cargo units and consumed inputs.
    ProducerIdentityFixture {
        #[arg(long)]
        output: PathBuf,
    },
    ProducerIdentity(Box<ProducerIdentityArgs>),
    /// Verify a reviewed provider association without Cargo discovery or building.
    VerifyNativeProvider {
        #[arg(long)]
        receipt: PathBuf,
        #[arg(long)]
        package_id: String,
        #[arg(long)]
        out_dir: PathBuf,
    },
    /// Independently verify actual deployed bytes and their current consumed inputs.
    VerifyDeploymentArtifact {
        #[arg(long)]
        receipt: PathBuf,
        #[arg(long)]
        artifact: PathBuf,
    },
    /// Observe complete dirty outer context without compiling it into consumers.
    ObserveDeployment {
        #[arg(long)]
        output: PathBuf,
    },
    /// Freeze independent FeOS PC-SAFT properties as typed oracle Parquet banks.
    #[cfg(feature = "thermodynamic-oracles")]
    FeosReference {
        output: PathBuf,
    },
    /// Run Python tests using their operation-owned canonical fixtures.
    #[cfg(feature = "package-fixtures")]
    PythonTests {
        #[arg(trailing_var_arg = true, allow_hyphen_values = true)]
        args: Vec<String>,
    },
    /// Assert one resolved version per dependency family, equal to the declared pin.
    FamilyCheck {
        /// Additional `Cargo.lock` files whose shared packages must agree with ours.
        #[arg(long, value_name = "LOCK")]
        evidence: Vec<PathBuf>,
        /// Compare only packages that belong to a declared family. The evidence lockfiles
        /// were resolved on their own day; unrelated transitive crates drift by patch
        /// version without telling us anything about the pins.
        #[arg(long)]
        evidence_families_only: bool,
    },
    /// Regenerate declared sources or check byte-for-byte regeneration equivalence.
    Codegen {
        /// Regenerate in scratch space and reject differing or untracked output.
        #[arg(long)]
        check: bool,
        /// Restrict to one generator.
        #[arg(long, value_enum, value_name = "TARGET")]
        only: Option<Target>,
    },
    /// Generate the exact compiled native Python API stub (run py-sync first).
    PythonStubs {
        /// Compare generated bytes without changing the committed stub.
        #[arg(long)]
        check: bool,
        /// Exact compiled extension; defaults to the checkout's active .venv module.
        #[arg(long)]
        extension: Option<PathBuf>,
    },
    /// The full governance gate: governance tests, codegen diff, family check.
    Governance,
    /// Resolve backticked API paths in `docs/**` against the extracted facts.
    DocLint,
    /// Report what this host can do: toolchain, Ipopt, external function libraries.
    ProbeHost {
        /// Emit JSON instead of a human-readable report.
        #[arg(long)]
        json: bool,
    },
}

/// Inputs to one producer derivation; boxed in the command enum.
#[derive(Debug, clap::Args)]
struct ProducerIdentityArgs {
    #[arg(long)]
    package: String,
    #[arg(long, default_value = "dev")]
    profile: String,
    #[arg(long)]
    target: Option<String>,
    /// Capture the package's library target (the default).
    #[arg(long, conflicts_with_all = ["bin", "cdylib_manifest"])]
    lib: bool,
    /// Capture only this production binary and its consumed dependencies.
    #[arg(long, conflicts_with_all = ["lib", "cdylib_manifest"])]
    bin: Option<String>,
    /// Capture the declared cdylib through Cargo rustc, as Maturin does.
    #[arg(long, conflicts_with_all = ["lib", "bin"])]
    cdylib_manifest: Option<PathBuf>,
    #[arg(long, value_delimiter = ',')]
    features: Vec<String>,
    #[arg(long)]
    no_default_features: bool,
    #[arg(long)]
    dep_info: Vec<PathBuf>,
    #[arg(long = "input")]
    declared_inputs: Vec<PathBuf>,
    #[arg(long)]
    native_input: Vec<PathBuf>,
    #[arg(long = "environment")]
    environment: Vec<String>,
    #[arg(long)]
    declarations: Option<PathBuf>,
    /// Private actual build/unit/command evidence for source review, not a grant.
    #[arg(long)]
    build_evidence: Option<PathBuf>,
    /// Refresh only selected build-script/proc-macro packages with Cargo clean
    /// in the selected profile before guarded actual capture.
    #[arg(long)]
    refresh_executors: bool,
    #[arg(long)]
    output: PathBuf,
}

/// Committed generators and the contract bootstrap phase.
#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
enum Target {
    /// `pse-schema` output: typed relation views.
    Relations,
    /// Rust registry contracts only, before rebuilding the ordinary package loader.
    RustContracts,
    /// `pse-schema` output: the Python contract classes.
    Python,
    /// `pse-schema` output: the reference tables in the book.
    Docs,
    /// Registry-generated canonical native schema and codecs.
    Surreal,
    /// `bindgen` output for the Ipopt C API.
    Bindgen,
    /// The JSON Schemas of the Rust-owned boundary documents and of the authoring
    /// documents, and the Python msgspec document types (ADR-0116 Outcome 7). Derived from
    /// the owning crates' types, so it needs the complete (package-fixtures) build.
    Schemas,
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    let root = workspace_root()?;
    match cli.command {
        #[cfg(feature = "canonical-tools")]
        Cmd::CanonicalInit { state } => {
            let options = pse_operations::canonical::CanonicalOptions::from_state(&state)?;
            let executor = tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()?;
            executor.block_on(async {
                let store = pse_operations::canonical::CanonicalStore::connect(&options).await?;
                store.create().await?;
                store.open().await
            })?;
            println!("canonical database initialized and interpretation verified");
            Ok(())
        }
        Cmd::ProducerIdentityFixture { output } => {
            producer_identity::qualified_fixture(&root, &output)?;
            Ok(())
        }
        Cmd::VerifyNativeProvider {
            receipt,
            package_id,
            out_dir,
        } => producer_identity::verify_native_provider(&receipt, &package_id, &out_dir),
        Cmd::VerifyDeploymentArtifact { receipt, artifact } => {
            producer_identity::verify_deployment_artifact(&receipt, &artifact)
        }
        Cmd::ObserveDeployment { output } => producer_identity::observe_deployment(&root, &output),
        Cmd::ProducerIdentity(args) => {
            let ProducerIdentityArgs {
                package,
                profile,
                target,
                lib: _,
                bin,
                cdylib_manifest,
                features,
                no_default_features,
                dep_info,
                declared_inputs,
                native_input,
                environment,
                declarations,
                build_evidence,
                refresh_executors,
                output,
            } = *args;
            let declared_environment = environment
                .into_iter()
                .map(|entry| {
                    let (key, value) = entry
                        .split_once('=')
                        .context("environment must be KEY=VALUE")?;
                    ensure!(!key.is_empty(), "environment key must be nonempty");
                    Ok((key.to_owned(), value.to_owned()))
                })
                .collect::<Result<BTreeMap<_, _>>>()?;
            let mut declarations: producer_identity::InputDeclarations = match declarations {
                Some(path) => serde_json::from_slice(&std::fs::read(path)?)?,
                None => producer_identity::InputDeclarations::default(),
            };
            if let Some(path) = build_evidence {
                declarations.actual_build_evidence = Some(path);
            }
            declarations.refresh_executors |= refresh_executors;
            let identity = producer_identity::run(&producer_identity::ProducerOptions {
                workspace_root: root,
                package,
                profile,
                target,
                production_target: match (bin, cdylib_manifest) {
                    (Some(name), _) => producer_identity::ProducerTarget::Binary(name),
                    (_, Some(manifest)) => producer_identity::ProducerTarget::Cdylib(manifest),
                    _ => producer_identity::ProducerTarget::Library,
                },
                features,
                no_default_features,
                dep_info,
                declared_inputs,
                native_inputs: native_input,
                declared_environment,
                declarations,
            })?;
            producer_identity::write_if_changed(&output, &identity)?;
            println!(
                "producer identity {}: persistent reuse eligible={}",
                identity.identity, identity.persistent_reuse_eligible
            );
            Ok(())
        }
        #[cfg(feature = "thermodynamic-oracles")]
        Cmd::FeosReference { output } => feos_reference::run(&root, &output),
        #[cfg(feature = "package-fixtures")]
        Cmd::PythonTests { args } => python_tests::run(&root, &args),
        Cmd::FamilyCheck {
            evidence,
            evidence_families_only,
        } => {
            family_check(&root, &default_evidence(), true)?;
            if evidence.is_empty() {
                Ok(())
            } else {
                family_check(&root, &evidence, evidence_families_only)
            }
        }
        Cmd::Codegen { check, only } => codegen(&root, check, only),
        Cmd::PythonStubs { check, extension } => {
            codegen::python_stubs::run(&root, extension.as_deref(), check)
        }
        Cmd::Governance => governance(&root),
        Cmd::DocLint => {
            println!("doc-lint: not implemented in phase 0 (see docs/adr/register.md)");
            std::process::exit(2);
        }
        Cmd::ProbeHost { json } => {
            probe_host(json);
            Ok(())
        }
    }
}

/// Resolve the runtime checkout, never the location baked into a cached executable.
fn workspace_root() -> Result<PathBuf> {
    let start = std::env::current_dir().context("reading invocation directory")?;
    workspace::find_workspace_root(&start).map_err(|error| anyhow!(error))
}

fn default_evidence() -> Vec<PathBuf> {
    EVIDENCE_LOCKS.iter().map(PathBuf::from).collect()
}

