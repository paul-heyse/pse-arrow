//! The maintained full CoolProp C ABI, including the matched saturation export.
use anyhow::{Context, Result, ensure};
use std::{fs, path::Path};

pub(super) fn run(root: &Path, check: bool) -> Result<()> {
    let header = root.join("vendor/coolprop-sys/CoolPropLib.h");
    let bindings = bindgen::Builder::default()
        .header(header.to_string_lossy())
        .derive_debug(true)
        .derive_default(true)
        .dynamic_library_name("CoolProp")
        .dynamic_link_require_all(true)
        .use_core()
        .generate_cstr(true)
        .generate_comments(false)
        .generate()
        .context("generating maintained CoolProp ABI")?;
    let output = root.join(super::provenance::protocol::COOLPROP_BINDINGS);
    let text =
        format!("// @generated by cargo xtask codegen --only bindgen; do not edit\n{bindings}");
    super::reject_symlinks(
        root,
        Path::new(super::provenance::protocol::COOLPROP_BINDINGS),
    )?;
    if check {
        ensure!(
            fs::read_to_string(&output)? == text,
            "CoolProp ABI differs; run just codegen --only bindgen"
        );
    } else if fs::read_to_string(&output).ok().as_deref() != Some(&text) {
        fs::write(&output, text)?;
    }
    println!(
        "codegen: CoolProp ABI {}",
        if check { "matches" } else { "generated" }
    );
    Ok(())
}
