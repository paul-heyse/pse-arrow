//! One publication route for source-owned Proto worlds, validators and provenance.

use anyhow::{Context, Result, bail, ensure};
use buffa_descriptor::generated::descriptor::FileDescriptorSet;
use pse_codegen::codegen::{GeneratedTree, boundary_projection, provenance};
use pse_contract::boundary_projection::ProjectionGraph;
use std::{
    collections::BTreeSet,
    path::{Component, Path, PathBuf},
};
mod composition;

/// One independently published consumer world and its source attribution.
pub(super) struct ProjectionTarget<'a> {
    pub package: &'a str,
    pub file: &'a str,
    pub destination: &'a str,
    pub rust_module: &'a str,
    pub document_root: &'a str,
    pub generator_path: &'a str,
    pub generator_symbol: &'a str,
}

pub(super) fn projection(
    graph: &ProjectionGraph,
    target: ProjectionTarget<'_>,
    imports: &FileDescriptorSet,
) -> Result<GeneratedTree> {
    let config =
        boundary_projection::default_config(&format!("{}::__buffa_fds", target.rust_module));
    let output = boundary_projection::generate_with_config(
        graph,
        target.package,
        target.file,
        &imports.file,
        &config,
    )?;
    publish_projection(graph, target, output)
}

/// Publish one actual generation closure. Callers can derive additional consumers
/// from its descriptor set and original configuration before transferring it here.
pub(super) fn publish_projection(
    graph: &ProjectionGraph,
    target: ProjectionTarget<'_>,
    output: boundary_projection::ProjectionOutput,
) -> Result<GeneratedTree> {
    let ProjectionTarget {
        package,
        file,
        destination,
        rust_module,
        document_root,
        generator_path,
        generator_symbol,
    } = target;
    ensure!(
        output.generation.targets() == [file],
        "projection publication target differs from its admitted generation"
    );
    for warning in &output.generation.warnings {
        eprintln!("{package} (Buffa): {warning}");
    }
    let destination = PathBuf::from(destination);
    let composed = composition::generate(&output.generation, rust_module)
        .with_context(|| format!("{package}: compose admitted source projection"))?;
    composed.admit(&output, &destination)?;
    let mut tree = GeneratedTree::empty(vec![destination.clone()]);
    for (name, source) in output.sources() {
        insert(&mut tree, &destination, name, source.as_bytes())?;
    }
    let policy = boundary_projection::native_policy_source(
        graph,
        package,
        pse_contract::BoundaryDirection::Both,
    )?;
    insert(
        &mut tree,
        &destination,
        "native-policy.rs",
        policy.as_bytes(),
    )?;
    insert(
        &mut tree,
        &destination,
        "descriptor.bin",
        &output.descriptor_bytes,
    )?;
    insert(
        &mut tree,
        &destination,
        "descriptor-source.bin",
        &output.source_descriptor_bytes,
    )?;
    composed.insert(&mut tree, &destination)?;
    let docs = PathBuf::from(document_root).join(package);
    insert(
        &mut tree,
        &docs,
        "index.md",
        format!(
            "<!-- @generated by pse-schema; do not edit -->\n{}",
            output.documentation
        )
        .as_bytes(),
    )?;
    tree.roots.push(docs);
    for definition in graph.definitions().values() {
        for path in tree.files.keys() {
            tree.relationships.push(provenance::SourceRelationship {
                declaration_key: definition.name.clone(),
                declaration_kind: "rust_projection".into(),
                source_path: Some(definition.source.into()),
                source_symbol: Some(definition.rust_type.into()),
                source_role: "semantic_owner".into(),
                source_identity: None,
                generator_path: generator_path.into(),
                generator_symbol: generator_symbol.into(),
                output_path: path.to_string_lossy().into_owned(),
                direction: Some(format!("{:?}", definition.direction)),
                contract_sections: vec!["blueprint §4.7".into()],
                basis: "declared".into(),
            });
        }
    }
    let sidecar = provenance::sidecar(&producer(package), &tree.relationships)?;
    merge_independent(&mut tree, sidecar)?;
    Ok(tree)
}

pub(super) fn producer(package: &str) -> String {
    package.replace(['.', '_'], "-")
}

/// Admit independent worlds before map extension can overwrite an earlier producer.
/// Same-producer provenance refresh is a separate, explicit caller operation.
pub(super) fn merge_independent(tree: &mut GeneratedTree, other: GeneratedTree) -> Result<()> {
    let mut roots = BTreeSet::new();
    for root in tree.roots.iter().chain(&other.roots) {
        if !roots.insert(root) {
            bail!("duplicate independent generated root: {}", root.display());
        }
    }
    admit_paths(tree.files.keys().chain(other.files.keys()).cloned())?;
    tree.roots.extend(other.roots);
    tree.files.extend(other.files);
    tree.relationships.extend(other.relationships);
    Ok(())
}

fn admit_paths(paths: impl IntoIterator<Item = PathBuf>) -> Result<()> {
    let mut admitted = BTreeSet::new();
    for path in paths {
        if path.as_os_str().is_empty()
            || path
                .components()
                .any(|part| !matches!(part, Component::Normal(_)))
        {
            bail!("unsafe generated output: {}", path.display());
        }
        if !admitted.insert(path.clone()) {
            bail!("duplicate generated output: {}", path.display());
        }
    }
    for path in &admitted {
        if path
            .ancestors()
            .skip(1)
            .any(|parent| admitted.contains(parent))
        {
            bail!("generated file/directory collision: {}", path.display());
        }
    }
    Ok(())
}

pub(super) fn insert(
    tree: &mut GeneratedTree,
    destination: &Path,
    name: &str,
    bytes: &[u8],
) -> Result<()> {
    let relative = Path::new(name);
    if relative.as_os_str().is_empty()
        || relative
            .components()
            .any(|part| !matches!(part, Component::Normal(_)))
    {
        bail!("unsafe generated output: {name}");
    }
    let path = destination.join(relative);
    admit_paths(
        tree.files
            .keys()
            .cloned()
            .chain(std::iter::once(path.clone())),
    )?;
    let bytes = if path.extension().is_some_and(|extension| extension == "rs") {
        super::code_intelligence::qualify_generated_rust(std::str::from_utf8(bytes)?)?.into_bytes()
    } else {
        bytes.to_vec()
    };
    tree.files.insert(path, bytes);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn source_projection_output_admission_rejects_duplicates_unsafe_paths_and_file_parents() {
        for paths in [
            vec!["world/a.rs", "world/a.rs"],
            vec!["world/a.rs", "world/a.rs/nested.rs"],
            vec!["world/../escaped.rs"],
            vec!["/absolute.rs"],
        ] {
            assert!(admit_paths(paths.into_iter().map(PathBuf::from)).is_err());
        }
    }

    #[test]
    fn independent_world_collision_refuses_before_replacing_original_output() {
        let mut original = GeneratedTree::empty(vec!["first".into()]);
        original
            .files
            .insert("first/item.rs".into(), b"original".to_vec());
        let mut duplicate = GeneratedTree::empty(vec!["second".into()]);
        duplicate
            .files
            .insert("first/item.rs".into(), b"replacement".to_vec());
        assert!(merge_independent(&mut original, duplicate).is_err());
        assert_eq!(original.files[Path::new("first/item.rs")], b"original");
        assert_eq!(original.roots, vec![PathBuf::from("first")]);
        assert!(insert(&mut original, Path::new("first"), "item.rs", b"replacement").is_err());
        assert_eq!(original.files[Path::new("first/item.rs")], b"original");
    }
}
