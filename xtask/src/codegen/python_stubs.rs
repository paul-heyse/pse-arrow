//! The actual PyO3 binary defines the Python API. Native exception declarations
//! supply only the fragment the pinned introspector cannot represent under abi3.
mod exceptions;
mod validate;

use anyhow::{Context, Result, bail, ensure};
use pse_codegen::codegen::{
    GeneratedTree,
    provenance::{self, SourceRelationship},
};
use pyo3_introspection::{introspect_cdylib, module_stub_files};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

const OUTPUT: &str = "python/pse/_native.pyi";
const HEADER: &str = "# SPDX-License-Identifier: MIT OR Apache-2.0\n# Copyright (c) 2026 Paul Heyse\n# @generated by cargo xtask python-stubs from actual PyO3 metadata; do not edit\n";

pub(crate) fn run(root: &Path, extension: Option<&Path>, check: bool) -> Result<()> {
    let extension =
        extension.map_or_else(|| installed_extension(root), |path| Ok(path.to_owned()))?;
    let mut module = introspect_cdylib(&extension, "_native").with_context(|| {
        format!(
            "introspecting {}; rebuild with just py-sync",
            extension.display()
        )
    })?;
    let exceptions = exceptions::read(&root.join("crates/pse-py/src/inspection/errors.rs"))?;
    let source = fs::read_to_string(root.join("crates/pse-py/src/lib.rs"))?;
    let classes = validate::read_class_names(&root.join("crates/pse-py/src"))?;
    validate::complete(&mut module, &source, exceptions, &classes)?;
    let mut files = module_stub_files(&module);
    ensure!(
        files.len() == 1,
        "native boundary unexpectedly contains Python submodules"
    );
    let body = files
        .remove(Path::new("__init__.pyi"))
        .context("native stub root missing")?;
    // Explicit PyO3 annotations can name typing without the introspector adding it.
    let imports = if body.contains("typing.") {
        "import typing\n"
    } else {
        ""
    };
    let output = format(root, &format!("{HEADER}{imports}{body}"))?;
    let provenance = provenance_tree(&output)?;
    let target = root.join(OUTPUT);
    super::reject_symlinks(root, Path::new(OUTPUT))?;
    if check {
        ensure!(
            fs::read(&target).with_context(|| format!("reading {}", target.display()))? == output,
            "native stub differs from actual compiled API; run just py-sync"
        );
    } else if !matches!(fs::read(&target), Ok(previous) if previous == output) {
        fs::write(&target, output).with_context(|| format!("writing {}", target.display()))?;
    }
    if check {
        let scratch = tempfile::tempdir().context("creating stub provenance comparison")?;
        super::write_tree(scratch.path(), &provenance)?;
        super::compare_tree(root, scratch.path(), &provenance)?;
        super::untracked_check(root, &provenance.roots)?;
    } else {
        super::write_tree(root, &provenance)?;
    }
    println!(
        "python-stubs{}: OK (actual compiled API)",
        if check { " --check" } else { "" }
    );
    Ok(())
}

/// The API identity hashes the actual formatted introspection result, rather than
/// an absolute binary path or build-dependent native object bytes.
fn provenance_tree(output: &[u8]) -> Result<GeneratedTree> {
    let identity = format!(
        "pyo3-stub-sha256:{}",
        Sha256::digest(output)
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>()
    );
    let mut records = Vec::new();
    for (kind, path, role) in [
        ("pyo3_metadata", None, "compiled_pyo3_metadata"),
        (
            "pyo3_module",
            Some("crates/pse-py/src/lib.rs"),
            "module_registration",
        ),
        (
            "pyo3_exception_supplement",
            Some("crates/pse-py/src/inspection/errors.rs"),
            "introspector_supplement",
        ),
    ] {
        records.push(SourceRelationship {
            declaration_key: "_native".into(),
            declaration_kind: kind.into(),
            source_path: path.map(str::to_owned),
            source_symbol: Some("_native".into()),
            source_role: role.into(),
            source_identity: Some(identity.clone()),
            generator_path: "xtask/src/codegen/python_stubs.rs".into(),
            generator_symbol: "run".into(),
            output_path: OUTPUT.into(),
            direction: None,
            contract_sections: vec!["21.5".into()],
            basis: "declared".into(),
        });
    }
    Ok(provenance::sidecar("native-stubs", &records)?)
}

/// The checkout's environment: `UV_PROJECT_ENVIRONMENT` when set, as uv and the recipes use it.
fn venv(root: &Path) -> PathBuf {
    let selected = std::env::var_os("UV_PROJECT_ENVIRONMENT")
        .map_or_else(|| PathBuf::from(".venv"), PathBuf::from);
    if selected.is_absolute() {
        selected
    } else {
        root.join(selected)
    }
}

pub(super) fn tool(root: &Path, name: &str) -> PathBuf {
    if cfg!(windows) {
        venv(root).join("Scripts").join(format!("{name}.exe"))
    } else {
        venv(root).join("bin").join(name)
    }
}
fn installed_extension(root: &Path) -> Result<PathBuf> {
    let output = Command::new(tool(root, "python"))
        .current_dir(root)
        .args(["-c", "from pse import _native; print(_native.__file__)"])
        .output()
        .context("finding the checkout's compiled extension; run just py-sync")?;
    ensure!(
        output.status.success(),
        "finding native extension: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let path = PathBuf::from(String::from_utf8(output.stdout)?.trim());
    ensure!(
        path.is_file(),
        "native extension path is absent: {}",
        path.display()
    );
    Ok(path)
}
fn format(root: &Path, source: &str) -> Result<Vec<u8>> {
    // Explicit PyO3 type strings arrive quoted (PYI020), and the introspector lists a
    // native `__repr__` that `object` already declares (PYI029). The pinned Python
    // parser normalizes both and sorts generator imports (I001).
    let normalized = ruff(
        root,
        source.as_bytes(),
        &["check", "--fix", "--select", "I001,PYI020,PYI029"],
    )?;
    ruff(root, &normalized, &["format"])
}
fn ruff(root: &Path, source: &[u8], args: &[&str]) -> Result<Vec<u8>> {
    ruff_for(root, source, args, OUTPUT)
}
/// Canonical generated implementation publication; retain ordinary lint visibility.
#[cfg(feature = "full-codegen")]
pub(super) fn format_projection(root: &Path, source: &[u8], output: &str) -> Result<Vec<u8>> {
    let initial = ruff_for(
        root,
        source,
        &["format", "--config", "format.exclude=[]"],
        output,
    )?;
    let normalized = ruff_for(root, &initial, &["check", "--fix"], output)?;
    let formatted = ruff_for(
        root,
        &normalized,
        &["format", "--config", "format.exclude=[]"],
        output,
    )?;
    ruff_for(root, &formatted, &["check"], output)?;
    Ok(formatted)
}
fn ruff_for(root: &Path, source: &[u8], args: &[&str], output: &str) -> Result<Vec<u8>> {
    let mut child = Command::new(tool(root, "ruff"))
        .current_dir(root)
        .args(args)
        .args(["--stdin-filename", output, "-"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("formatting native stub with pinned ruff")?;
    child
        .stdin
        .take()
        .context("ruff stdin absent")?
        .write_all(source)?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "formatting native stub: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(output.stdout)
}

#[cfg(test)]
mod provenance_tests {
    use super::*;

    #[test]
    fn actual_stub_producer_is_distinct_from_catalogue_and_tracks_api_bytes() {
        let tree = provenance_tree(b"class Native: ...\n").unwrap();
        let path = Path::new(provenance::ROOT).join("native-stubs/relationships.json");
        let value: serde_json::Value = serde_json::from_slice(&tree.files[&path]).unwrap();
        let records = value["relationships"].as_array().unwrap();
        assert!(records.iter().all(|record| record["generator_path"]
            == "xtask/src/codegen/python_stubs.rs"
            && record["output_path"] == "python/pse/_native.pyi"));
        assert!(
            records
                .iter()
                .any(|record| record["declaration_kind"] == "pyo3_metadata"
                    && record["source_path"].is_null())
        );
        assert!(
            records
                .iter()
                .all(|record| record["contract_sections"] == serde_json::json!(["21.5"]))
        );
        assert_ne!(
            tree.files,
            provenance_tree(b"class Changed: ...\n").unwrap().files
        );
        assert_eq!(tree, provenance_tree(b"class Native: ...\n").unwrap());
    }
}
