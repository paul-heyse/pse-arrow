//! The supplier prost declarations own borrowed predecode wire shapes.
use anyhow::{Context, Result, bail};
use pse_codegen::codegen::GeneratedTree;
use std::{
    path::{Path, PathBuf},
    process::Command,
};

pub(super) fn append(root: &Path, tree: &mut GeneratedTree) -> Result<()> {
    let destination = PathBuf::from("crates/pse-operations/src/generated");
    if !tree.roots.contains(&destination) {
        bail!("protocol wire shapes must be appended to the existing Surreal output owner");
    }
    let metadata = Command::new("cargo")
        .args(["metadata", "--locked", "--format-version", "1"])
        .current_dir(root)
        .output()
        .context("resolve pinned protocol generator input")?;
    if !metadata.status.success() {
        bail!(
            "protocol source resolution failed: {}",
            String::from_utf8_lossy(&metadata.stderr)
        );
    }
    let metadata: serde_json::Value = serde_json::from_slice(&metadata.stdout)?;
    let packages = metadata["packages"]
        .as_array()
        .context("Cargo metadata packages")?;
    let protocol = packages
        .iter()
        .find(|p| p["name"] == "surrealdb-protocol")
        .context("resolved protocol package")?;
    if protocol["version"] != "0.13.1" {
        bail!("borrowed wire generator requires reviewed protocol 0.13.1");
    }
    let manifest = protocol["manifest_path"]
        .as_str()
        .context("protocol manifest path")?;
    let source = Path::new(manifest)
        .parent()
        .context("protocol source root")?;
    let python = root.join(if cfg!(windows) {
        ".venv/Scripts/python.exe"
    } else {
        ".venv/bin/python"
    });
    let rendered = Command::new(python)
        .arg(root.join("scripts/grpc_wire_schema.py"))
        .arg(source)
        .current_dir(root)
        .output()
        .context("render protocol borrowed wire shapes")?;
    if !rendered.status.success() {
        bail!(
            "protocol wire rendering failed: {}",
            String::from_utf8_lossy(&rendered.stderr)
        );
    }
    let parsed = syn::parse_file(std::str::from_utf8(&rendered.stdout)?)?;
    tree.files.insert(destination.join("grpc_wire_schema.rs"),
        format!("// SPDX-License-Identifier: MIT OR Apache-2.0\n// Copyright (c) 2026 Paul Heyse\n// @generated by xtask grpc-wire; do not edit\n#![rustfmt::skip]\n{}", prettyplease::unparse(&parsed)).into_bytes());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn wrong_output_owner_refuses_before_source_resolution_or_publication() {
        let mut tree = GeneratedTree::empty(vec![PathBuf::from("crates/pse-model/src/generated")]);
        let roots = tree.roots.clone();
        let error = append(Path::new("not-a-checkout"), &mut tree).unwrap_err();
        assert!(error.to_string().contains("existing Surreal output owner"));
        assert_eq!(tree.roots, roots);
        assert!(tree.files.is_empty());
    }
}
