//! Independent registry lowering for the disposable tooling database.
use super::GeneratedTree;
use pse_schema::{Registry, SchemaError};
use quote::quote;
use std::path::PathBuf;
pub(super) fn append(registry: &Registry, tree: &mut GeneratedTree) -> Result<(), SchemaError> {
    let knowledge_digest = append_knowledge(registry, tree)?;
    let selected = registry
        .relations()
        .iter()
        .filter(|r| r.key.name.starts_with("evidence_"))
        .collect::<Vec<_>>();
    let (ddl, codecs) = pse_codegen::codegen::native_relations(
        registry,
        selected.iter().copied(),
        xtask::development::catalog::evidence::INDEXES,
    )?;
    let interpretation = xtask::development::catalog::evidence::INTERPRETATION;
    let mut digest = pse_ids::FramedHasher::new(pse_ids::Frame::CanonicalSchemaV1);
    digest
        .str(interpretation)
        .part(ddl.as_bytes())
        .str(&knowledge_digest);
    for codec in &codecs {
        digest.str(&codec.to_string());
    }
    let schema_digest = digest.finish_hash().to_hex();
    let owned_codecs = pse_codegen::codegen::family::development_native_codecs(&codecs)?;
    let source = quote! {
        /// Independent tooling interpretation.
        pub const INTERPRETATION:&str=#interpretation;
        /// Tooling-only schema and codec compatibility identity.
        pub const SCHEMA_DIGEST:&str=#schema_digest;
        /// Tooling-only registry declarations.
        pub const SCHEMA:&str=include_str!("evidence.surql");
        #owned_codecs
    };
    let parsed = syn::parse2::<syn::File>(source).map_err(|e| SchemaError::Codegen {
        language: "surreal",
        reason: e.to_string(),
    })?;
    tree.files.insert(
        PathBuf::from("xtask/src/generated/store/evidence.surql"),
        ddl.into_bytes(),
    );
    tree.files.insert(PathBuf::from("xtask/src/generated/store/evidence.rs"),format!("// SPDX-License-Identifier: MIT OR Apache-2.0\n// Copyright (c) 2026 Paul Heyse\n// @generated by pse-schema; do not edit\n{}",prettyplease::unparse(&parsed)).into_bytes());
    record_relationships(
        registry,
        tree,
        &selected,
        &[
            "xtask/src/generated/store/evidence.rs",
            "xtask/src/generated/store/evidence.surql",
        ],
        "append",
    );
    Ok(())
}

fn record_relationships(
    registry: &Registry,
    tree: &mut GeneratedTree,
    relations: &[&pse_schema::model::RelationSpec],
    outputs: &[&str],
    symbol: &str,
) {
    for relation in relations {
        for output in outputs {
            tree.relationships
                .push(super::provenance::SourceRelationship::registry(
                    registry,
                    "relation",
                    super::provenance::relation_key(relation),
                    "xtask/src/codegen/private_store.rs",
                    symbol,
                    *output,
                ));
        }
    }
}

fn append_knowledge(registry: &Registry, tree: &mut GeneratedTree) -> Result<String, SchemaError> {
    use xtask::development::catalog::knowledge as declaration;
    use std::fmt::Write as _;
    let selected = registry
        .relations()
        .iter()
        .filter(|relation| relation.key.name.starts_with("knowledge_"))
        .collect::<Vec<_>>();
    let (mut ddl, codecs) =
        pse_codegen::codegen::native_relations(registry, selected.iter().copied(), declaration::INDEXES)?;
    knowledge_constraints(&mut ddl);
    let search = &declaration::FULL_TEXT;
    let relation = registry
        .relation(&format!("runtime.{}", search.table))
        .ok_or_else(|| SchemaError::Codegen {
            language: "surreal",
            reason: "knowledge full-text table absent".into(),
        })?;
    if !relation.columns.iter().any(|field| {
        field.name() == search.field
            && field.value_type().data_type() == arrow_schema::DataType::Utf8
    }) {
        return Err(SchemaError::Codegen {
            language: "surreal",
            reason: "knowledge full-text field is not a declared string".into(),
        });
    }
    let _ = writeln!(
        ddl,
        "DEFINE ANALYZER {} TOKENIZERS {} FILTERS {};",
        search.analyzer,
        declaration::TOKENIZERS.join(","),
        declaration::FILTERS.join(",")
    );
    let _ = writeln!(
        ddl,
        "DEFINE INDEX {} ON {} FIELDS {} FULLTEXT ANALYZER {} BM25;",
        search.name, search.table, search.field, search.analyzer
    );
    let interpretation = declaration::INTERPRETATION;
    let mut digest = pse_ids::FramedHasher::new(pse_ids::Frame::CanonicalSchemaV1);
    digest.str(interpretation).part(ddl.as_bytes());
    for codec in &codecs {
        digest.str(&codec.to_string());
    }
    let schema_digest = digest.finish_hash().to_hex();
    let owned_codecs = pse_codegen::codegen::family::development_native_codecs(&codecs)?;
    let source = quote! {
        /// Independent development knowledge interpretation.
        pub const INTERPRETATION: &str = #interpretation;
        /// Exact knowledge schema and codec identity.
        pub const SCHEMA_DIGEST: &str = #schema_digest;
        /// Registry-derived tooling-only knowledge schema.
        pub const SCHEMA: &str = include_str!("knowledge.surql");
        #owned_codecs
    };
    let parsed = syn::parse2::<syn::File>(source).map_err(|cause| SchemaError::Codegen {
        language: "surreal",
        reason: cause.to_string(),
    })?;
    tree.files.insert(
        "xtask/src/generated/store/knowledge.surql".into(),
        ddl.into_bytes(),
    );
    tree.files.insert(
        "xtask/src/generated/store/knowledge.rs".into(),
        format!(
            "// @generated by pse-schema; do not edit\n{}",
            prettyplease::unparse(&parsed)
        )
        .into_bytes(),
    );
    record_relationships(
        registry,
        tree,
        &selected,
        &[
            "xtask/src/generated/store/knowledge.rs",
            "xtask/src/generated/store/knowledge.surql",
        ],
        "append_knowledge",
    );
    Ok(schema_digest)
}

fn knowledge_constraints(ddl: &mut String) {
    use xtask::development::catalog::knowledge as declaration;
    use std::fmt::Write as _;
    let strings = |values: &[&str]| {
        format!(
            "[{}]",
            values
                .iter()
                .map(|value| format!("'{value}'"))
                .collect::<Vec<_>>()
                .join(",")
        )
    };
    let mut subjects = Vec::new();
    for policy in declaration::SUBJECTS {
        let mut conditions = vec![format!("$value='{}'", policy.kind)];
        conditions.push(if policy.roles.is_empty() {
            "$this.document_role=NONE".into()
        } else {
            format!("$this.document_role IN {}", strings(policy.roles))
        });
        if policy.requires_state {
            conditions.push("$this.native_state!=NONE AND $this.state_basis!=NONE".into());
        }
        if !policy.permits_state {
            conditions.push("$this.native_state=NONE AND $this.state_basis=NONE AND $this.publication_scope=NONE".into());
        } else {
            conditions.push("(($this.native_state=NONE AND $this.state_basis=NONE) OR ($this.native_state!=NONE AND $this.state_basis!=NONE))".into());
        }
        if policy.requires_version {
            conditions.push("$this.native_version!=NONE".into());
        }
        let evidence = if policy.evidence { "!=NONE" } else { "=NONE" };
        for field in [
            "evidence_authority",
            "evidence_codec",
            "evidence_source",
            "evidence_version",
            "evidence_member",
        ] {
            conditions.push(format!("$this.{field}{evidence}"));
        }
        if !policy.bases.is_empty() {
            conditions.push(format!("$this.basis IN {}", strings(policy.bases)));
        }
        subjects.push(format!("({})", conditions.join(" AND ")));
    }
    let kinds = declaration::SUBJECTS
        .iter()
        .map(|policy| format!("'{}'", policy.kind))
        .collect::<Vec<_>>()
        .join(" | ");
    let _ = writeln!(
        ddl,
        "DEFINE FIELD OVERWRITE kind ON knowledge_subjects TYPE {kinds} READONLY ASSERT {};",
        subjects.join(" OR ")
    );
    let mut edges = Vec::new();
    for policy in declaration::RELATIONS {
        edges.push(format!(
            "($value='{}' AND $this.in.kind IN {} AND $this.out.kind IN {}{})",
            policy.kind,
            strings(policy.from),
            strings(policy.to),
            if policy.same_kind {
                " AND $this.in.kind=$this.out.kind"
            } else {
                ""
            }
        ));
    }
    let kinds = declaration::RELATIONS
        .iter()
        .map(|policy| format!("'{}'", policy.kind))
        .collect::<Vec<_>>()
        .join(" | ");
    let _ = writeln!(
        ddl,
        "DEFINE FIELD OVERWRITE relation ON knowledge_subject_edges TYPE {kinds} READONLY ASSERT {};",
        edges.join(" OR ")
    );
    let _ = writeln!(
        ddl,
        "DEFINE FIELD OVERWRITE topic ON knowledge_subject_topics TYPE string READONLY ASSERT {{ LET $knowledge_assert_generation=$this.generation; LET $knowledge_assert_subject=$this.subject_key; LET $knowledge_assert_source=$this.source_key; RETURN $this.subject_key_record.kind IN ['document','contract','decision','plan_package'] AND array::len((SELECT VALUE key FROM knowledge_subject_sources WHERE generation=$knowledge_assert_generation AND subject_key=$knowledge_assert_subject AND source_key=$knowledge_assert_source AND role='metadata' LIMIT 1))=1; }};"
    );
    // Optional-field ASSERTs are skipped for NONE. Own the pairing invariant on
    // a required field so omission of the physical alias cannot bypass it.
    let _ = writeln!(
        ddl,
        "DEFINE FIELD OVERWRITE excerpt_id ON knowledge_excerpts TYPE string READONLY ASSERT {{ LET $knowledge_assert_generation=$this.generation; LET $knowledge_assert_subject=$this.subject_key; LET $knowledge_assert_source=$this.source_key; RETURN ($this.subject_key=NONE AND $this.subject_key_record=NONE) OR ($this.subject_key!=NONE AND $this.subject_key_record=type::record('knowledge_subjects',$this.subject_key) AND record::exists($this.subject_key_record) AND $this.subject_key_record.generation=$this.generation AND array::len((SELECT VALUE key FROM knowledge_subject_sources WHERE generation=$knowledge_assert_generation AND subject_key=$knowledge_assert_subject AND source_key=$knowledge_assert_source LIMIT 1))=1); }};"
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn knowledge_schema_is_tooling_only_with_declared_fulltext_and_native_graph() {
        let registry = xtask::development::catalog::assemble().unwrap();
        let canonical = pse_codegen::codegen::canonical_schema(&pse_schema::catalog::assemble().unwrap()).unwrap();
        assert!(!canonical.contains("knowledge_"));
        let mut tree = GeneratedTree::empty(vec![PathBuf::from("xtask/src/generated")]);
        append(&registry, &mut tree).unwrap();
        let ddl = std::str::from_utf8(
            &tree.files
                [std::path::Path::new("xtask/src/generated/store/knowledge.surql")],
        )
        .unwrap();
        assert!(ddl.contains("DEFINE TABLE knowledge_subject_edges TYPE RELATION IN knowledge_subjects OUT knowledge_subjects ENFORCED"));
        assert!(ddl.contains("DEFINE ANALYZER knowledge_text_v2 TOKENIZERS blank,class,camel,punct FILTERS lowercase;"));
        assert!(ddl.contains("DEFINE INDEX knowledge_excerpt_text ON knowledge_excerpts FIELDS text FULLTEXT ANALYZER knowledge_text_v2 BM25;"));
        assert!(ddl.contains("REFERENCE ON DELETE REJECT READONLY ASSERT $value=type::record('knowledge_subjects',$this.generator_key)"));
        assert!(ddl.contains("DEFINE FIELD OVERWRITE excerpt_id ON knowledge_excerpts TYPE string READONLY ASSERT { LET $knowledge_assert_generation=$this.generation;"));
        assert!(
            tree.relationships
                .iter()
                .any(
                    |record| record.declaration_key == "runtime.knowledge_subject_edges@1"
                        && record.output_path
                            == "xtask/src/generated/store/knowledge.surql"
                )
        );
        let original = std::str::from_utf8(
            &tree.files[std::path::Path::new("xtask/src/generated/store/evidence.surql")],
        )
        .unwrap();
        assert!(
            !original.contains("knowledge_"),
            "original evidence codecs/schema remain separate"
        );
    }
}
