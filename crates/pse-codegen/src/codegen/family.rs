//! Responsibility-local output context for the existing Rust renderer.
use super::{GeneratedTree, rust};
use crate::{Registry, SchemaError};
use std::path::PathBuf;
use syn::visit_mut::VisitMut;

/// Private values and native relation codecs use the same admitted renderer as product rows.
/// Only their owner paths and output destinations differ; product files are never selected.
/// # Errors
/// A registry construct unsupported by the existing renderer or malformed Rust output.
pub fn development_rust(registry: &Registry) -> Result<GeneratedTree, SchemaError> {
    let original = rust::generate(registry)?;
    let root = PathBuf::from("xtask/src/generated");
    let mut tree = GeneratedTree::empty(vec![root.clone()]);
    tree.files.insert(root.join("mod.rs"), b"// @generated by pse-schema; do not edit\n//! Private development contracts.\npub mod model;\npub mod relations;\npub mod store;\n".to_vec());
    for (path, bytes) in original.files {
        let (relative, model) =
            if let Ok(relative) = path.strip_prefix("crates/pse-model/src/generated") {
                (PathBuf::from("model").join(relative), true)
            } else if let Ok(relative) = path.strip_prefix("crates/pse-relations/src/generated") {
                (PathBuf::from("relations").join(relative), false)
            } else {
                continue;
            };
        // These projections belong to scientific compilation/selection, not this private store.
        if relative.file_name().is_some_and(|name| {
            matches!(
                name.to_str(),
                Some(
                    "products.rs"
                        | "facts.rs"
                        | "algorithm_arguments.rs"
                        | "result_selection.rs"
                        | "extension_values.rs"
                        | "identities.rs"
                )
            )
        }) {
            continue;
        }
        let mut syntax = syn::parse_file(
            std::str::from_utf8(&bytes).map_err(|cause| rust::error(cause.to_string()))?,
        )
        .map_err(|cause| rust::error(cause.to_string()))?;
        if relative.file_name().is_some_and(|name| name == "mod.rs") {
            syntax.items.retain(|item| !matches!(item, syn::Item::Mod(module) if matches!(module.ident.to_string().as_str(), "products" | "facts" | "algorithm_arguments" | "result_selection" | "extension_values" | "identities")));
        }
        OwnerPaths {
            model,
            store: false,
        }
        .visit_file_mut(&mut syntax);
        let output = root.join(relative);
        for mut relationship in original
            .relationships
            .iter()
            .filter(|row| PathBuf::from(&row.output_path) == path)
            .cloned()
        {
            relationship.output_path = output.to_string_lossy().into_owned();
            relationship.generator_path = "crates/pse-codegen/src/codegen/family.rs".into();
            relationship.generator_symbol = "development_rust".into();
            tree.relationships.push(relationship);
        }
        tree.files.insert(
            output,
            format!(
                "// @generated by pse-schema; do not edit\n{}",
                prettyplease::unparse(&syntax)
            )
            .into_bytes(),
        );
    }
    Ok(tree)
}

struct OwnerPaths {
    model: bool,
    store: bool,
}
impl VisitMut for OwnerPaths {
    // Visibility is relative to the destination crate; it is not a referenced type path.
    fn visit_visibility_mut(&mut self, _visibility: &mut syn::Visibility) {}

    fn visit_item_use_mut(&mut self, item: &mut syn::ItemUse) {
        if let syn::UseTree::Path(first) = &item.tree
            && first.ident == "pse_model"
            && let syn::UseTree::Path(second) = first.tree.as_ref()
            && second.ident == "generated"
        {
            let suffix = second.tree.as_ref();
            item.tree = syn::parse_quote!(crate::generated::model::#suffix);
        } else {
            syn::visit_mut::visit_item_use_mut(self, item);
        }
    }
    fn visit_lit_str_mut(&mut self, literal: &mut syn::LitStr) {
        if literal.value() == "pse_model::" {
            *literal = syn::LitStr::new("xtask::generated::model::", literal.span());
        }
    }
    fn visit_path_mut(&mut self, path: &mut syn::Path) {
        let names = path
            .segments
            .iter()
            .map(|part| part.ident.to_string())
            .collect::<Vec<_>>();
        let prefix: syn::Path;
        let skip;
        if names.starts_with(&["pse_model".into(), "generated".into()]) {
            prefix = syn::parse_quote!(crate::generated::model);
            skip = 2;
        } else if names.starts_with(&["pse_schema".into(), "registry".into()]) {
            prefix = syn::parse_quote!(crate::development::registry);
            skip = 2;
        } else if names.starts_with(&["crate".into(), "generated".into()]) {
            prefix = if self.model {
                syn::parse_quote!(crate::generated::model)
            } else {
                syn::parse_quote!(crate::generated::relations)
            };
            skip = 2;
        } else if names.first().is_some_and(|name| name == "crate") {
            prefix = if self.store {
                syn::parse_quote!(pse_operations)
            } else if self.model {
                syn::parse_quote!(pse_model)
            } else {
                syn::parse_quote!(pse_relations)
            };
            skip = 1;
        } else {
            syn::visit_mut::visit_path_mut(self, path);
            return;
        }
        let suffix = path.segments.iter().skip(skip).cloned().collect::<Vec<_>>();
        *path = prefix;
        path.segments.extend(suffix);
        for segment in &mut path.segments {
            self.visit_path_arguments_mut(&mut segment.arguments);
        }
    }
}

/// Bind the existing native store codec renderer to private values and shared exact scalar codecs.
/// # Errors
/// The rendered source is not valid Rust.
pub fn development_native_codecs(
    codecs: &[proc_macro2::TokenStream],
) -> Result<proc_macro2::TokenStream, SchemaError> {
    let mut syntax = syn::parse2::<syn::File>(quote::quote!(#(#codecs)*))
        .map_err(|cause| rust::error(cause.to_string()))?;
    OwnerPaths {
        model: false,
        store: true,
    }
    .visit_file_mut(&mut syntax);
    Ok(quote::quote!(#syntax))
}
