    fn python_documents_are_closed_typed_structs() {
        let registry = crate::registry().unwrap();
        let schema = serde_json::json!({
            "title": "Probe",
            "type": "object",
            "additionalProperties": false,
            "required": ["version", "choice"],
            "properties": {
                "version": {"type": "integer", "const": 1, "default": 1},
                "hessian": {"$ref": "#/$defs/HessianMode", "default": "limited_memory"},
                "choice": {"$ref": "#/$defs/Choice"},
                "budget": {"$ref": "#/$defs/Budget", "default": 0.5},
                "items": {"type": "array", "items": {"type": "string"}, "default": []},
                "pair": {"type": ["array", "null"], "items": {"type": "number"}, "minItems": 2, "maxItems": 2, "default": null},
            },
            "$defs": {
                "HessianMode": {"type": "string", "enum": ["exact", "limited_memory"]},
                "Budget": {"type": "number", "exclusiveMinimum": 0.0},
                "Choice": {"oneOf": [
                    {"type": "object", "additionalProperties": false, "required": ["kind"],
                     "properties": {"kind": {"type": "string", "const": "plain"}}},
                    {"type": "object", "additionalProperties": false, "required": ["kind", "size"],
                     "properties": {"kind": {"type": "string", "const": "sized"},
                                    "size": {"type": "integer", "minimum": 1}}},
                ]},
            },
        });
        let source = python(registry, &[document(schema)]).unwrap();
        for expected in [
            "Budget = Annotated[float, msgspec.Meta(gt=0.0)]",
            "class ChoicePlain(msgspec.Struct, frozen=True, forbid_unknown_fields=True, kw_only=True, tag_field=\"kind\", tag=\"plain\"):",
            "    size: Annotated[int, msgspec.Meta(ge=1)]",
            "Choice = ChoicePlain | ChoiceSized",
            "    version: Literal[1] = 1",
            "    hessian: enums.HessianMode = enums.HessianMode.LIMITED_MEMORY",
            "    choice: Choice\n",
            "    items: tuple[str, ...] = msgspec.field(default_factory=tuple)",
            "    pair: tuple[float, float] | None = None",
        ] {
            assert!(source.contains(expected), "{expected}\n{source}");
        }
        assert!(!source.contains("Any"));
    }

    #[test]
    fn non_registry_enumerations_and_open_objects_are_refused() {
        let registry = crate::registry().unwrap();
        let enumeration = serde_json::json!({
            "title": "Probe", "type": "object", "additionalProperties": false,
            "required": ["mode"],
            "properties": {"mode": {"$ref": "#/$defs/Mode"}},
            "$defs": {"Mode": {"type": "string", "enum": ["a", "b"]}},
        });
        assert!(python(registry, &[document(enumeration)]).is_err());
        let open = serde_json::json!({
            "title": "Probe", "type": "object", "required": [],
            "properties": {"x": {"type": "number", "default": 1.0}},
        });
        assert!(python(registry, &[document(open)]).is_err());
        let wrong = serde_json::json!({
            "title": "Probe", "type": "object", "additionalProperties": false,
            "required": ["hessian"],
            "properties": {"hessian": {"$ref": "#/$defs/HessianMode"}},
            "$defs": {"HessianMode": {"type": "string", "enum": ["exact"]}},
        });
        assert!(python(registry, &[document(wrong)]).is_err());
    }

