//! Independent registry lowering for the disposable tooling database.
use super::GeneratedTree;
use crate::{Registry, SchemaError};
use quote::quote;
use std::path::PathBuf;
pub(super) fn append(registry:&Registry,tree:&mut GeneratedTree)->Result<(),SchemaError>{
    let (ddl,codecs)=super::surreal::relations(registry,registry.relations().iter().filter(|r|r.key.name.starts_with("evidence_")),pse_schema::catalog::evidence::INDEXES)?;
    let interpretation=pse_schema::catalog::evidence::INTERPRETATION;
    let mut digest=pse_ids::FramedHasher::new(pse_ids::Frame::CanonicalSchemaV1);
    digest.str(interpretation).part(ddl.as_bytes());
    for codec in &codecs {digest.str(&codec.to_string());}
    let schema_digest=digest.finish_hash().to_hex();
    let source=quote!{
        /// Independent tooling interpretation.
        pub const INTERPRETATION:&str=#interpretation;
        /// Tooling-only schema and codec compatibility identity.
        pub const SCHEMA_DIGEST:&str=#schema_digest;
        /// Tooling-only registry declarations.
        pub const SCHEMA:&str=include_str!("evidence.surql");
        #(#codecs)*
    };
    let parsed=syn::parse2::<syn::File>(source).map_err(|e|SchemaError::Codegen{language:"surreal",reason:e.to_string()})?;
    tree.files.insert(PathBuf::from("crates/pse-operations/src/generated/evidence.surql"),ddl.into_bytes());
    tree.files.insert(PathBuf::from("crates/pse-operations/src/generated/evidence.rs"),format!("// SPDX-License-Identifier: MIT OR Apache-2.0\n// Copyright (c) 2026 Paul Heyse\n// @generated by pse-schema; do not edit\n{}",prettyplease::unparse(&parsed)).into_bytes());
    Ok(())
}
