//! Explicit eager-view adoption using the selected generator's real naming context.
use super::*;
use buffa_descriptor::generated::descriptor::FileDescriptorSet;

/// Actual generation inputs for one selected eager-view native crossing.
#[derive(Debug, Clone, Copy)]
pub struct NativeViewTarget<'a> {
    /// Complete descriptor world used for the selected Buffa generation.
    pub descriptors: &'a FileDescriptorSet,
    /// Actual source file requested from that generation.
    pub selected_file: &'a str,
    /// Same configuration used to generate the eager views.
    pub config: &'a buffa_codegen::CodeGenConfig,
    /// Consumer path to this source file's generated package module.
    pub wire_root: &'a str,
    /// Consumer crate for source-owned native public aliases.
    pub owner_crate: &'a str,
    /// Reachability of root wrappers, independently of strict adoption semantics.
    pub visibility: AdapterVisibility,
}

/// Emit borrowed adoption for exactly the selected Data roots and their closure.
/// The view is validated before native construction; no owned protobuf tree or
/// dynamic intermediate is created. Observation-only owners have no inverse.
pub fn native_view_adapters(
    graph: &ProjectionGraph,
    roots: &[&str],
    target: NativeViewTarget<'_>,
) -> Result<String, ProjectionCodegenError> {
    if !target.config.generate_views {
        return Err(error(
            "selected native view crossing requires eager views in its actual generation profile",
        ));
    }
    if !target.config.preserve_unknown_fields {
        return Err(error(
            "strict native view adoption requires preserving original unknown fields",
        ));
    }
    if roots.is_empty() {
        return Err(error("native view adoption needs explicit selected roots"));
    }
    syn::parse_str::<syn::Path>(target.wire_root)
        .map_err(|source| error(format!("invalid eager-view package path: {source}")))?;
    let file = target
        .descriptors
        .file
        .iter()
        .find(|file| file.name.as_deref() == Some(target.selected_file))
        .ok_or_else(|| error("selected eager-view source descriptor is absent"))?;
    let package = file.package.as_deref().unwrap_or_default();
    let requested = vec![target.selected_file.into()];
    let naming = buffa_codegen::context::CodeGenContext::for_generate(
        &target.descriptors.file,
        &requested,
        target.config,
    );
    let source = Generator {
        wire_root: target.wire_root,
        owner_crate: target.owner_crate,
        retained_wire: false,
        naming: &naming,
        graph,
    };
    let generator = Borrowed {
        source: &source,
        package,
    };
    let mut selected = BTreeSet::new();
    for root in roots {
        select(graph, root, &mut selected)?;
    }
    for name in &selected {
        if graph.definitions()[name].construction != ConstructionRole::Data {
            return Err(error(format!(
                "{name}: borrowed adoption cannot reconstruct an observation-only native owner"
            )));
        }
        if !file
            .message_type
            .iter()
            .any(|message| message.name.as_deref() == Some(name.as_str()))
        {
            return Err(error(format!(
                "{name}: selected native owner has no eager-view declaration in the requested file"
            )));
        }
    }
    let mut out = String::new();
    for name in &selected {
        generator.owner(&graph.definitions()[name], &mut out)?;
    }
    for name in roots {
        let native = source.native(&graph.definitions()[*name])?;
        let view = generator.view(&[(*name).into()], "'_")?;
        let method = snake_case(name);
        let visibility = target.visibility.rust();
        let _ = writeln!(
            out,
            "/// Validate and adopt the selected native `{name}` directly from its eager view.\n{visibility} fn decode_{method}_view(wire: &{view}) -> Result<{native}, BoundaryProjectionError> {{ decode_view_root(wire,{name:?}) }}"
        );
    }
    let helpers = [
        "NativeFrom",
        "BoundaryProjectionError",
        "native_from",
        "decode_view_root",
        "unknown_fields_view",
        "layout",
        "child_path",
        "required",
        "refused",
        "from_items",
        "unique_pairs",
    ];
    let used = |name: &str| {
        out.split(|character: char| !character.is_ascii_alphanumeric() && character != '_')
            .any(|token| token == name)
    };
    let imports = helpers
        .into_iter()
        .filter(|helper| used(helper))
        .collect::<Vec<_>>()
        .join(",");
    let core = ["AdapterError", "AdapterFailure"]
        .into_iter()
        .filter(|helper| used(helper))
        .collect::<Vec<_>>()
        .join(",");
    let source = format!(
        "// @generated by pse-codegen from selected native eager-view owners; do not edit.\nuse pse_contract_proto::support::{{{imports}}};\nuse pse_contract::boundary_projection::{{{core}}};\n{out}"
    );
    let parsed = syn::parse_file(&source).map_err(|source| {
        error(format!(
            "borrowed native adapter rendering failed: {source}"
        ))
    })?;
    Ok(prettyplease::unparse(&parsed))
}

#[cfg(test)]
mod tests {
    use super::*;
    use pse_contract::boundary_projection::Direction;
    pse_contract::projection_enum! {
        pub(super) enum Outcome {
            projection:{name:"Outcome",version:1,direction:Direction::Both,reserved_tags:[],reserved_names:[]};
            Values(Vec<f64>) => 1;
            Empty => 2;
        }
    }
    pse_contract::projection_struct! {
        pub(super) struct BorrowedFixture {
            projection:{name:"BorrowedFixture",version:1,direction:Direction::Both,reserved_tags:[],reserved_names:[]};
            exact:Option<i128> => {tag:1,direction:Direction::Both,rules:[]};
            factors:Vec<i8> => {tag:2,direction:Direction::Both,rules:[]};
            labels:std::collections::BTreeMap<String,Vec<Option<u64>>> => {tag:3,direction:Direction::Both,rules:[]};
            identities:std::collections::BTreeMap<pse_ids::SemanticId,String> => {tag:4,direction:Direction::Both,rules:[]};
            outcome:Outcome => {tag:5,direction:Direction::Both,rules:[]};
        }
    }
    #[test]
    fn borrowed_emission_uses_real_view_paths_and_logical_map_semantics() {
        let graph = ProjectionGraph::of::<BorrowedFixture>().unwrap();
        let descriptors = crate::codegen::boundary_projection::descriptors_with_imports(
            &graph,
            "pse.borrowed.v1",
            "borrowed.proto",
            &crate::codegen::boundary_projection::tests::imports(),
        )
        .unwrap();
        let config = buffa_codegen::CodeGenConfig::default();
        let target = NativeViewTarget {
            descriptors: &descriptors,
            selected_file: "borrowed.proto",
            config: &config,
            wire_root: "crate::pb",
            owner_crate: "pse_codegen",
            visibility: AdapterVisibility::Parent,
        };
        let rendered = native_view_adapters(&graph, &["BorrowedFixture"], target).unwrap();
        syn::parse_file(&rendered).unwrap();
        for expected in [
            "BorrowedFixtureView<'buffer>",
            "OutcomeView<'_>",
            "iter_unique()",
            "unique_pairs",
            "unknown_fields_view",
            "decode_view_root",
            "from_projection_slice",
        ] {
            assert!(rendered.contains(expected), "{expected}: {rendered}");
        }
        let requested = vec!["borrowed.proto".into()];
        let naming = buffa_codegen::context::CodeGenContext::for_generate(
            &descriptors.file,
            &requested,
            &config,
        );
        assert!(
            naming
                .rust_type_relative_split(
                    ".pse.borrowed.v1.BorrowedFixture.Field3Value",
                    "pse.borrowed.v1",
                    0
                )
                .is_some(),
            "map value wrapper names come from the actual linked generation world"
        );
        for forbidden in [
            "to_owned_message",
            "DynamicMessage",
            "NativeInto",
            ".clone()",
        ] {
            assert!(!rendered.contains(forbidden), "{forbidden}");
        }
        let mut unavailable = config.clone();
        unavailable.generate_views = false;
        assert!(
            native_view_adapters(
                &graph,
                &["BorrowedFixture"],
                NativeViewTarget {
                    config: &unavailable,
                    ..target
                }
            )
            .is_err()
        );
        unavailable = config.clone();
        unavailable.preserve_unknown_fields = false;
        assert!(
            native_view_adapters(
                &graph,
                &["BorrowedFixture"],
                NativeViewTarget {
                    config: &unavailable,
                    ..target
                }
            )
            .is_err()
        );
    }
    #[test]
    fn borrowed_emission_never_reconstructs_observation_only_native_owners() {
        pse_contract::projection_struct! {
            struct Observation {
                projection:{name:"Observation",version:1,direction:Direction::Output,construction:ObservationOnly,reserved_tags:[],reserved_names:[]};
                count:u64 => {tag:1,direction:Direction::Output,rules:[]};
            }
        }
        let graph = ProjectionGraph::of::<Observation>().unwrap();
        let descriptors = crate::codegen::boundary_projection::descriptors_with_imports(
            &graph,
            "pse.borrowed.v1",
            "borrowed.proto",
            &crate::codegen::boundary_projection::tests::imports(),
        )
        .unwrap();
        let config = buffa_codegen::CodeGenConfig::default();
        assert!(
            native_view_adapters(
                &graph,
                &["Observation"],
                NativeViewTarget {
                    descriptors: &descriptors,
                    selected_file: "borrowed.proto",
                    config: &config,
                    wire_root: "crate::pb",
                    owner_crate: "pse_codegen",
                    visibility: AdapterVisibility::Parent
                }
            )
            .is_err()
        );
    }
}

struct Borrowed<'a, 'b> {
    source: &'a Generator<'b>,
    package: &'a str,
}
impl Borrowed<'_, '_> {
    fn view(&self, path: &[String], lifetime: &str) -> Result<String, ProjectionCodegenError> {
        let fqn = format!(".{}.{}", self.package, path.join("."));
        super::super::local_view_path(self.source.naming, self.package,
            self.source.wire_root, &fqn, "View", lifetime)
    }
    fn guard(&self, value: &str, path: &str) -> String {
        format!("unknown_fields_view(&{value}.__buffa_unknown_fields,{path})?;")
    }
    fn fields(
        &self,
        fields: &[Field],
        parent: &[String],
    ) -> Result<String, ProjectionCodegenError> {
        let mut out = String::from("(");
        for field in fields {
            let name = buffa_codegen::idents::make_field_ident(&field.name);
            let path = format!("&child_path(path,{:?})", field.name);
            let input = if requires_scalar_presence(field) {
                format!("required(wire.{name}.as_ref(),{path})?")
            } else {
                format!("&wire.{name}")
            };
            let value = self.decode(&field.ty, &input, &path, parent, field.tag, false)?;
            let _ = write!(out, "{value},");
        }
        out.push(')');
        Ok(out)
    }
    fn owner(&self, owner: &Definition, out: &mut String) -> Result<(), ProjectionCodegenError> {
        let native = self.source.native(owner)?;
        let parent = vec![owner.name.clone()];
        let view = self.view(&parent, "'buffer")?;
        let guard = self.guard("wire", "path");
        let _ = write!(
            out,
            "impl<'buffer> NativeFrom<&{view}> for {native} {{ fn from_wire(wire:&{view},path:&str)->Result<Self,AdapterError>{{{guard}"
        );
        match &owner.shape {
            Shape::Record(fields) => {
                let layout =
                    self.source
                        .layout(&native, fields, owner.version, None, owner.checked_record);
                let accessor = if owner.checked_record {
                    "CheckedProjectionRecord"
                } else {
                    "ProjectionRecord"
                };
                let fields = self.fields(fields, &parent)?;
                let _ = write!(
                    out,
                    "{layout}let fields={fields};pse_contract::boundary_projection::{accessor}::from_projection_fields(fields).map_err(|source|source.at(path))"
                );
            }
            Shape::Alternatives(arms) => {
                let module = buffa_codegen::idents::escape_mod_ident(
                    &self
                        .source
                        .naming
                        .nested_module_name(self.package, &owner.name),
                );
                let kind = format!(
                    "{}::__buffa::view::oneof::{module}::Kind",
                    self.source.wire_root
                );
                let _ = write!(
                    out,
                    "match wire.kind.as_ref().ok_or_else(||refused(path,AdapterFailure::UnknownAlternative,\"required alternative is absent\"))?{{"
                );
                for arm in arms {
                    let variant =
                        buffa_codegen::idents::to_upper_camel_case(&snake_case(&arm.name));
                    let nested = self
                        .source
                        .nested(&parent, format!("Alternative{}", arm.tag));
                    let layout = self.source.layout(
                        &native,
                        &arm.fields,
                        owner.version,
                        Some(arm.tag),
                        false,
                    );
                    let fields = self.fields(&arm.fields, &nested)?;
                    let guard = self.guard("wire", "path");
                    let _ = write!(
                        out,
                        "{kind}::{variant}(wire)=>{{let alternative_path=child_path(path,{:?});let path=alternative_path.as_str();{guard}{layout}let fields={fields};Ok(<{native} as pse_contract::boundary_projection::ProjectionAlternative<{}>>::from_projection_alternative(fields))}},",
                        arm.name, arm.tag
                    );
                }
                out.push('}');
            }
            Shape::StringEnum(_) => {
                out.push_str("wire.value.parse::<Self>().map_err(|_|refused(path,AdapterFailure::UnknownAlternative,\"unknown canonical source vocabulary member\"))");
            }
        }
        out.push_str("}}\n");
        Ok(())
    }
    fn decode(
        &self,
        ty: &TypeRef,
        value: &str,
        path: &str,
        parent: &[String],
        tag: u32,
        raw: bool,
    ) -> Result<String, ProjectionCodegenError> {
        Ok(match ty {
            TypeRef::Scalar(Scalar::Bytes | Scalar::SemanticId | Scalar::ContentHash) => format!(
                "pse_contract::boundary_projection::ProjectionBytes::from_projection_slice(*({value}),{path})?"
            ),
            TypeRef::Scalar(Scalar::String) => format!("native_from::<_,&str>(*({value}),{path})?"),
            TypeRef::Scalar(Scalar::I128Bits) => {
                format!("native_from::<_,&[u8]>(*({value}),{path})?")
            }
            TypeRef::Scalar(scalar) => format!(
                "native_from::<_,{}>(*({value}),{path})?",
                scalar_wire(*scalar)
            ),
            TypeRef::Named(name) => {
                let actual = if raw {
                    value.to_owned()
                } else {
                    format!("required(({value}).as_option(),{path})?")
                };
                let view = self.view(&[name.clone()], "'_")?;
                format!("native_from::<_,&{view}>({actual},{path})?")
            }
            TypeRef::Optional(inner) => {
                let input = if matches!(inner.as_ref(), TypeRef::Scalar(_)) {
                    format!("({value}).as_ref()")
                } else {
                    format!("({value}).as_option()")
                };
                let converted = if matches!(inner.as_ref(), TypeRef::Scalar(_) | TypeRef::Named(_))
                {
                    self.decode(inner, "value", path, parent, tag, true)?
                } else {
                    self.wrapper(inner, "value", path, parent, tag)?
                };
                format!(
                    "{input}.map(|value|->Result<_,AdapterError>{{Ok({converted})}}).transpose()?"
                )
            }
            TypeRef::Repeated(inner) | TypeRef::Set(inner) => {
                let indexed = "&format!(\"{current_path}[{index}]\")";
                let converted = if matches!(inner.as_ref(), TypeRef::Scalar(_) | TypeRef::Named(_))
                {
                    self.decode(inner, "value", indexed, parent, tag, true)?
                } else {
                    self.wrapper(inner, "value", indexed, parent, tag)?
                };
                format!(
                    "{{let current_path={path};let values=({value}).iter().enumerate().map(|(index,value)|->Result<_,AdapterError>{{Ok({converted})}}).collect::<Result<Vec<_>,_>>()?;from_items(values,current_path)?}}"
                )
            }
            TypeRef::Map(key, item) => {
                let entry = self.source.nested(parent, format!("Field{tag}Entry"));
                if protobuf_map_key(key) {
                    let key = self.decode(key, "key", path, &entry, 1, true)?;
                    let item = if matches!(item.as_ref(), TypeRef::Scalar(_) | TypeRef::Named(_)) {
                        self.decode(item, "value", path, &entry, 2, true)?
                    } else {
                        self.wrapper(item, "value", path, parent, tag)?
                    };
                    format!(
                        "unique_pairs(({value}).iter_unique().map(|(key,value)|->Result<_,AdapterError>{{Ok(({key},{item}))}}).collect::<Result<Vec<_>,_>>()?,{path})?"
                    )
                } else {
                    let key = self.decode(key, "&entry.key", path, &entry, 1, false)?;
                    let item = self.decode(item, "&entry.value", path, &entry, 2, false)?;
                    let guard = self.guard("entry", path);
                    format!(
                        "unique_pairs(({value}).iter().map(|entry|->Result<_,AdapterError>{{{guard}Ok(({key},{item}))}}).collect::<Result<Vec<_>,_>>()?,{path})?"
                    )
                }
            }
        })
    }
    fn wrapper(
        &self,
        inner: &TypeRef,
        value: &str,
        path: &str,
        parent: &[String],
        tag: u32,
    ) -> Result<String, ProjectionCodegenError> {
        let nested = self.source.nested(parent, format!("Field{tag}Value"));
        let guard = self.guard("wrapped", path);
        let decoded = self.decode(inner, "&wrapped.value", path, &nested, 1, false)?;
        Ok(format!("{{let wrapped={value};{guard}{decoded}}}"))
    }
}
