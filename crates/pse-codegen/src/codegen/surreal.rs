//! Surreal lowerings of registry-owned canonical envelopes.

use super::GeneratedTree;
use crate::{Registry, SchemaError};
use arrow_schema::DataType;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use std::{fmt::Write as _, path::PathBuf};

/// Lower one explicitly selected database family with the shared exact native codecs.
pub(super) fn relations<'a>(
    registry: &Registry,
    relations: impl Iterator<Item = &'a pse_schema::model::RelationSpec>,
    indexes: &[pse_schema::catalog::substrate::NativeIndex],
) -> Result<(String, Vec<TokenStream>), SchemaError> {
    let mut ddl = String::from("-- @generated by pse-schema; do not edit\n");
    let mut codecs = Vec::new();
    for relation in relations {
        let table = relation.key.name;
        let endpoints = relation
            .columns
            .iter()
            .filter_map(|column| column.graph_endpoint().map(|endpoint| (endpoint, column)))
            .collect::<Vec<_>>();
        if endpoints.is_empty() {
            let caches = if pse_schema::catalog::substrate::INLINE_VERTICES.contains(&table) {
                " INLINE EDGES 64 INLINE REFERENCES 32"
            } else {
                ""
            };
            let _ = writeln!(ddl, "DEFINE TABLE {table} SCHEMAFULL{caches};");
        } else {
            let target = |endpoint: &str| -> Result<&str, SchemaError> {
                endpoints.iter().find(|(name,_)| *name == endpoint).and_then(|(_,column)| column.fk()).and_then(|fk| fk.relation.strip_prefix("runtime.")).ok_or_else(|| SchemaError::Codegen { language: "surreal", reason: format!("{table} graph endpoint {endpoint} requires a declared runtime record target") })
            };
            let _ = writeln!(
                ddl,
                "DEFINE TABLE {table} TYPE RELATION IN {} OUT {}{} SCHEMAFULL;",
                target("in")?,
                target("out")?,
                if pse_schema::catalog::substrate::ENFORCED_RELATIONS.contains(&table) {
                    " ENFORCED"
                } else {
                    ""
                }
            );
        }
        let module = format_ident!("{table}");
        let row_name = format_ident!("Runtime{}Row", super::rust::types::pascal(table));
        let row_path = quote!(pse_model::generated::runtime::#module::#row_name);
        let encode = format_ident!("encode_{table}");
        let decode = format_ident!("decode_{table}");
        let mut encoders = Vec::new();
        let mut decoders = Vec::new();
        let mut link_decoders = Vec::new();
        for column in &relation.columns {
            let name = column.name();
            let ident = format_ident!("r#{name}");
            if let Some(endpoint) = column.graph_endpoint() {
                let target = column
                    .fk()
                    .and_then(|fk| fk.relation.strip_prefix("runtime."))
                    .ok_or_else(|| SchemaError::Codegen {
                        language: "surreal",
                        reason: format!("{table}.{name} graph endpoint lacks its record target"),
                    })?;
                let _ = writeln!(
                    ddl,
                    "DEFINE FIELD OVERWRITE {endpoint} ON {table} TYPE record<{target}> ASSERT $value = type::record('{target}', $this.{name});"
                );
                encoders.push(quote! { object.insert(#endpoint, crate::canonical_codec::record_link(#target, &row.#ident)); });
                link_decoders.push(quote! { crate::canonical_codec::check_record_link(&mut object, #endpoint, #target, &row.#ident)?; });
            }
            let (ty, codec) = match column.value_type().data_type() {
                DataType::Utf8 => ("string", "string"),
                DataType::Binary => ("bytes", "bytes"),
                DataType::FixedSizeBinary(16) => ("bytes", "id"),
                DataType::UInt64 => ("decimal", "uint"),
                DataType::Int64 | DataType::Timestamp(_, _) => ("int", "int"),
                DataType::Boolean => ("bool", "boolean"),
                DataType::Float64 => ("object", "finite"),
                other => {
                    return Err(SchemaError::Codegen {
                        language: "surreal",
                        reason: format!(
                            "unsupported declared canonical field {table}.{name}: {other:?}"
                        ),
                    });
                }
            };
            let enum_type = column
                .enum_name()
                .map(|name| format_ident!("{}", super::rust::types::pascal(name)));
            let literal_ty = if let Some(name) = column.enum_name() {
                registry
                    .enum_spec(name)
                    .ok_or_else(|| SchemaError::Codegen {
                        language: "surreal",
                        reason: format!("unknown canonical enum {name}"),
                    })?
                    .members
                    .iter()
                    .map(|member| format!("\"{}\"", member.name))
                    .collect::<Vec<_>>()
                    .join(" | ")
            } else {
                ty.to_owned()
            };
            let declared_ty = if column.nullable() {
                format!("option<{literal_ty}>")
            } else {
                literal_ty
            };
            let assertion = if name == "key" {
                " ASSERT $value = record::id($this.id)"
            } else if codec == "id" {
                " ASSERT $value = NONE OR bytes::len($value) = 16"
            } else if ty == "decimal" {
                " ASSERT $value = NONE OR ($value >= 0dec AND $value <= 18446744073709551615dec AND math::floor($value) = $value)"
            } else if ty == "object" {
                " ASSERT $value = NONE OR ($value.projection >= -1.7976931348623157e308f AND $value.projection <= 1.7976931348623157e308f)"
            } else {
                ""
            };
            let readonly = if name == "key"
                || matches!(
                    table,
                    "canonical_project_operations"
                        | "canonical_research_references"
                        | "canonical_project_contexts"
                        | "canonical_context_ancestry"
                        | "canonical_project_draft_versions"
                        | "canonical_project_ancestry"
                        | "canonical_draft_diagnostics"
                )
                || (table == "canonical_project_branches"
                    && matches!(name, "project" | "problem" | "origin_revision"))
                || (table == "canonical_attempts"
                    && pse_schema::catalog::substrate::IMMUTABLE_ATTEMPT_FIELDS.contains(&name))
                || (table == "canonical_studies"
                    && pse_schema::catalog::substrate::IMMUTABLE_STUDY_FIELDS.contains(&name))
            {
                " READONLY"
            } else {
                ""
            };
            let assertion = if table == "canonical_attempts" && name == "phase" {
                let transitions = pse_schema::catalog::substrate::ATTEMPT_TRANSITIONS
                    .iter()
                    .map(|(before, after)| format!("($before='{before}' AND $value='{after}')"))
                    .collect::<Vec<_>>()
                    .join(" OR ");
                // Input-admission attempts own no native result inventory. Ordinary
                // attempts cannot skip closure/manifest publication. Completion is
                // separately compactable after terminal retention release. The
                // nonoptional phase assertion owns absence checks: native optional
                // field assertions are skipped when their value becomes NONE.
                format!(
                    " ASSERT ($before=NONE AND $value='ingesting' OR $before=$value OR {transitions} OR (string::starts_with($this.run,'study-admission:') AND $before IN ['ingesting','closed_awaiting_manifest','closed_with_manifest'] AND $value='terminal')) AND (($value='ingesting' AND $this.close_generation=NONE AND $this.closed_manifest=NONE AND $this.outcome=NONE AND $this.completion=NONE AND $this.seed_manifest=NONE) OR ($value='closed_awaiting_manifest' AND $this.close_generation!=NONE AND $this.closed_manifest=NONE AND $this.outcome=NONE AND $this.completion=NONE AND $this.seed_manifest=NONE) OR ($value='closed_with_manifest' AND $this.close_generation!=NONE AND $this.closed_manifest!=NONE AND $this.outcome=NONE AND $this.completion=NONE AND $this.seed_manifest=NONE) OR ($value IN ['terminal','terminal_compacted'] AND (($value='terminal_compacted' AND $this.completion=NONE) OR ($value='terminal' AND ((string::starts_with($this.run,'study-admission:') AND $this.outcome='failed' AND $this.completion=NONE) OR ($this.completion!=NONE AND !(string::starts_with($this.run,'study-admission:') AND $this.outcome='failed'))))) AND $this.outcome IN ['succeeded','failed','partial','cancelled'] AND (string::starts_with($this.run,'study-admission:') OR ($this.close_generation!=NONE AND $this.closed_manifest!=NONE))))"
                )
            } else if table == "canonical_attempts" && name == "outcome" {
                " ASSERT $before=NONE OR $before=$value".to_owned()
            } else if table == "canonical_attempts" && name == "closed_manifest" {
                " ASSERT ($value=NONE OR $value=$this.key) AND ($before=NONE OR $before=$value)"
                    .to_owned()
            } else if table == "canonical_attempts" && name == "completion" {
                " ASSERT ($this.phase!='terminal_compacted' OR $value=NONE) AND ($before=NONE OR $before=$value OR ($value=NONE AND $this.phase='terminal_compacted'))".to_owned()
            } else if table == "canonical_studies" && name == "next_ordinal" {
                " ASSERT $value>=0dec AND $value<=18446744073709551615dec AND math::floor($value)=$value AND $value<=$this.point_count AND ($before=NONE OR $value>=$before) AND (!$this.active OR $value=$this.point_count)".to_owned()
            } else if table == "canonical_studies" && name == "installed_dependencies" {
                " ASSERT $value>=0dec AND $value<=18446744073709551615dec AND math::floor($value)=$value AND $value<=$this.dependency_count AND ($before=NONE OR $value>=$before) AND (!$this.active OR ($value=$this.dependency_count AND $this.next_ordinal=$this.point_count))".to_owned()
            } else {
                assertion.to_owned()
            };
            let _ = writeln!(
                ddl,
                "DEFINE FIELD {name} ON {table} TYPE {declared_ty}{readonly}{assertion};"
            );
            if ty == "object" {
                let _ = writeln!(
                    ddl,
                    "DEFINE FIELD {name}.bits ON {table} TYPE option<bytes> ASSERT ($this.{name} = NONE AND $value = NONE) OR ($value != NONE AND bytes::len($value) = 8);\nDEFINE FIELD {name}.projection ON {table} TYPE option<float> ASSERT ($this.{name} = NONE AND $value = NONE) OR ($value >= -1.7976931348623157e308f AND $value <= 1.7976931348623157e308f);"
                );
            }
            if let Some(enum_type) = enum_type {
                if column.nullable() {
                    encoders.push(quote! { if let Some(value) = row.#ident { object.insert(#name, crate::canonical_codec::encode_string(value.as_str().to_owned())?); } });
                    decoders.push(quote! { #ident: match object.remove(#name) { None | Some(surrealdb::types::Value::None) => None, Some(value) => Some(crate::canonical_codec::decode_string(value)?.parse::<pse_model::generated::enums::#enum_type>().map_err(|_| crate::canonical_codec::CodecError::Domain(#name))?), } });
                } else {
                    encoders.push(quote! { object.insert(#name, crate::canonical_codec::encode_string(row.#ident.as_str().to_owned())?); });
                    decoders.push(quote! { #ident: crate::canonical_codec::decode_string(crate::canonical_codec::required(&mut object, #name)?)?.parse::<pse_model::generated::enums::#enum_type>().map_err(|_| crate::canonical_codec::CodecError::Domain(#name))? });
                }
                continue;
            }
            let encode_field = format_ident!("encode_{codec}");
            let decode_field = format_ident!("decode_{codec}");
            let copy = matches!(codec, "uint" | "int" | "boolean" | "finite" | "id");
            if column.nullable() {
                let value = if copy {
                    quote!(*value)
                } else {
                    quote!(value.clone())
                };
                encoders.push(quote! { if let Some(value) = &row.#ident { object.insert(#name, crate::canonical_codec::#encode_field(#value)?); } });
                decoders.push(quote! { #ident: match object.remove(#name) { None | Some(surrealdb::types::Value::None) => None, Some(value) => Some(crate::canonical_codec::#decode_field(value)?), } });
            } else {
                let value = if copy {
                    quote!(row.#ident)
                } else {
                    quote!(row.#ident.clone())
                };
                encoders.push(quote! { object.insert(#name, crate::canonical_codec::#encode_field(#value)?); });
                decoders.push(quote! { #ident: crate::canonical_codec::#decode_field(crate::canonical_codec::required(&mut object, #name)?)? });
            }
        }
        codecs.push(quote! {
            #[doc = "Encode the registry row using native exact values."]
            pub fn #encode(row: &#row_path) -> Result<surrealdb::types::Object, crate::canonical_codec::CodecError> {
                let mut object = surrealdb::types::Object::new();
                #(#encoders)*
                Ok(object)
            }
            #[doc = "Decode the registry row; native id metadata is distinct from the declared key."]
            pub fn #decode(mut object: surrealdb::types::Object) -> Result<#row_path, crate::canonical_codec::CodecError> {
                let native_id = object.remove("id");
                let row = #row_path { #(#decoders,)* };
                if let Some(native_id) = native_id { crate::canonical_codec::check_record_identity(native_id, #table, &row.r#key)?; }
                #(#link_decoders)*
                if !object.is_empty() { return Err(crate::canonical_codec::CodecError::UnknownFields); }
                Ok(row)
            }
        });
    }
    // Physical access paths are declared beside their canonical relation authority.
    for index in indexes {
        let relation = registry
            .relations()
            .iter()
            .find(|relation| relation.key.name == index.table)
            .ok_or_else(|| SchemaError::Codegen {
                language: "surreal",
                reason: format!("index {} names an undeclared table", index.name),
            })?;
        for field in index.fields {
            let (name, path) = field
                .split_once('.')
                .map_or((*field, None), |(name, path)| (name, Some(path)));
            if !relation.columns.iter().any(|column| {
                column.name() == name
                    && (path.is_none()
                        || (path == Some("projection")
                            && column.value_type().data_type() == DataType::Float64))
            }) {
                return Err(SchemaError::Codegen {
                    language: "surreal",
                    reason: format!("index {} names an undeclared field {field}", index.name),
                });
            }
        }
        let _ = writeln!(
            ddl,
            "DEFINE INDEX {} ON {} FIELDS {}{};",
            index.name,
            index.table,
            index.fields.join(", "),
            if index.unique { " UNIQUE" } else { "" }
        );
    }
    Ok((ddl, codecs))
}

pub(super) fn append(registry: &Registry, tree: &mut GeneratedTree) -> Result<(), SchemaError> {
    let indexes = pse_schema::catalog::substrate::INDEXES
        .iter()
        .chain(pse_schema::catalog::projects::NATIVE_INDEXES)
        .chain(pse_schema::catalog::project_contexts::NATIVE_INDEXES)
        .chain(pse_schema::catalog::study_workbench::NATIVE_INDEXES)
        .copied()
        .collect::<Vec<_>>();
    let (mut ddl, codecs) = relations(
        registry,
        registry
            .relations()
            .iter()
            .filter(|relation| relation.key.name.starts_with("canonical_")),
        &indexes,
    )?;
    let immutable_terminal_publication =
        pse_schema::catalog::substrate::TERMINAL_IMMUTABLE_ATTEMPT_FIELDS
            .iter()
            .map(|field| format!("$before.{field}!=$after.{field}"))
            .collect::<Vec<_>>()
            .join(" OR ");
    let seed_refusal = pse_schema::catalog::canonical_refusals::RefusalCode::ExecutionTerminalSeedManifestImmutable.wire();
    // A default event runs synchronously inside this transaction. Optional field
    // ASSERTs skip NONE and cannot protect either clearing or later resurrection.
    let _ = writeln!(
        ddl,
        "DEFINE EVENT pse_attempt_terminal_publication_immutable ON canonical_attempts WHEN $event='UPDATE' AND $before.phase IN ['terminal','terminal_compacted'] AND ({immutable_terminal_publication}) THEN {{ THROW '{seed_refusal}'; }};"
    );
    ddl.push_str(
        r#"
DEFINE FUNCTION fn::pse_execution_v1::deadline($rpc_expiry: int) -> bool {
    IF time::micros() >= $rpc_expiry { THROW 'PSE_REFUSAL:original_canonical_rpc_deadline_expired'; };
    RETURN true;
};
"#,
    );
    super::surreal_execution::append(&mut ddl);
    super::surreal_projects::append(&mut ddl);
    super::surreal_contexts::append(&mut ddl);
    super::surreal_files::append(&mut ddl);
    super::surreal_maintenance::append(&mut ddl);
    super::surreal_studies::append(&mut ddl);
    super::surreal_study_workbench::append(&mut ddl);
    super::surreal_retention::append(&mut ddl);
    super::surreal_analyses::append(&mut ddl);
    super::surreal_artifacts::append(&mut ddl);
    super::surreal_history::append(&mut ddl);
    for statement in ddl.split("THROW '").skip(1) {
        let code = statement.split('\'').next().unwrap_or("");
        if pse_schema::catalog::canonical_refusals::RefusalCode::parse(code).is_none() {
            return Err(SchemaError::Codegen {
                language: "surreal",
                reason: format!("undeclared canonical refusal {code}"),
            });
        }
    }
    let interpretation = pse_schema::catalog::substrate::INTERPRETATION;
    let mut digest = pse_ids::FramedHasher::new(pse_ids::Frame::CanonicalSchemaV1);
    digest.str(interpretation).part(ddl.as_bytes());
    for code in pse_schema::catalog::canonical_refusals::RefusalCode::ALL {
        digest.str(code.wire()).str(&format!("{:?}", code.class()));
    }
    for codec in &codecs {
        digest.str(&codec.to_string());
    }
    let schema_digest = digest.finish_hash().to_hex();
    let block_bytes = pse_schema::catalog::substrate::RESULT_BLOCK_BYTES;
    let file_target_bytes = pse_schema::catalog::substrate::RESULT_FILE_TARGET_BYTES;
    let index_bytes = pse_schema::catalog::substrate::RESULT_INDEX_BYTES;
    let message_bytes = pse_schema::catalog::substrate::RESULT_MESSAGE_BYTES;
    let index_records = pse_schema::catalog::substrate::RESULT_INDEX_RECORDS;
    let source: TokenStream = quote! {
        /// Registry-owned physical scientific block admission.
        pub const RESULT_BLOCK_BYTES: usize = #block_bytes;
        /// Preferred completed native IPC file packing extent.
        pub const RESULT_FILE_TARGET_BYTES: usize = #file_target_bytes;
        /// Registry-owned native encoded metadata envelope admission.
        pub const RESULT_INDEX_BYTES: usize = #index_bytes;
        /// Registry-owned complete selected transport envelope admission.
        pub const RESULT_MESSAGE_BYTES: usize = #message_bytes;
        /// Derived defensive metadata loop ceiling, independent of framing.
        pub const RESULT_INDEX_RECORDS: usize = #index_records;
        /// Exact interpretation of schema, codec and structural operations.
        pub const INTERPRETATION: &str = #interpretation;
        /// Exact generated schema and codec compatibility identity.
        pub const SCHEMA_DIGEST: &str = #schema_digest;
        /// Registry-derived database declarations.
        pub const SCHEMA: &str = include_str!("surreal.surql");
        #(#codecs)*
    };
    let file = syn::parse2::<syn::File>(source).map_err(|error| SchemaError::Codegen {
        language: "surreal",
        reason: error.to_string(),
    })?;
    tree.files.insert(
        PathBuf::from("crates/pse-operations/src/generated/surreal.surql"),
        ddl.into_bytes(),
    );
    tree.files.insert(PathBuf::from("crates/pse-operations/src/generated/surreal.rs"), format!("// SPDX-License-Identifier: MIT OR Apache-2.0\n// Copyright (c) 2026 Paul Heyse\n// @generated by pse-schema; do not edit\n\n{}", prettyplease::unparse(&file)).into_bytes());
    let policy = serde_json::to_vec_pretty(&serde_json::json!({
        "generated_by": "pse-schema", "interpretation": interpretation,
        "result_block_bytes": block_bytes, "result_file_target_bytes": file_target_bytes, "result_index_bytes": index_bytes,
        "max_message_bytes": message_bytes, "result_index_records": index_records,
    }))
    .map_err(|error| SchemaError::Codegen {
        language: "surreal",
        reason: error.to_string(),
    })?;
    tree.files.insert(
        PathBuf::from("crates/pse-operations/src/generated/surreal-policy.json"),
        policy,
    );
    Ok(())
}
