pub(super) fn error(reason: String) -> SchemaError {
    SchemaError::Codegen {
        language: "rust",
        reason,
    }
}

fn emit(
    tree: &mut GeneratedTree,
    path: impl Into<PathBuf>,
    tokens: TokenStream,
) -> Result<(), SchemaError> {
    let file = syn::parse2::<syn::File>(tokens).map_err(|error_| error(error_.to_string()))?;
    tree.files.insert(
        path.into(),
        format!("{HEADER}{}", prettyplease::unparse(&file)).into_bytes(),
    );
    Ok(())
}

