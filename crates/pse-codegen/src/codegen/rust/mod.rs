fn extension_values() -> Result<TokenStream, SchemaError> {
    let mut declarations = Vec::new();
    for use_ in [
        ExtensionUse::DimensionVector,
        ExtensionUse::QuantityValue,
        ExtensionUse::Bound,
        ExtensionUse::SourceSpan,
    ] {
        let name = types::pascal(&use_.name());
        let storage_name = format!("Extension{name}");
        let ty = types::storage(&use_.spec().storage(), &storage_name, &mut declarations)?;
        {
            let name = format_ident!("{}", name);
            declarations.push(
                quote!(#[doc = "The declared composite extension storage."] pub type #name = #ty;),
            );
        }
    }
    Ok(quote!(#(#declarations)*))
}

