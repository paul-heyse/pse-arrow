//! Readable projections of the registry; the declaration remains the authority.

use std::fmt::Write as _;

use std::collections::BTreeMap;

use crate::model::{EXTENSION_TYPES, FieldContract, QuantityContract};
use crate::{Registry, SchemaError};

use super::{GeneratedTree, Language};

const HEADER: &str = "<!-- @generated by pse-schema; do not edit -->\n\n";

fn emit(tree: &mut GeneratedTree, name: &str, mut source: String) {
    source.truncate(source.trim_end().len());
    source.push('\n');
    source.insert_str(0, HEADER);
    tree.files.insert(
        format!("docs/generated/{name}.md").into(),
        source.into_bytes(),
    );
}

struct MarkdownPolicy;
impl super::native::Policy for MarkdownPolicy {
    type Value = String;

    fn child_stem(
        &self,
        _field: &FieldContract,
        stem: &str,
        child: &arrow_schema::Field,
    ) -> String {
        format!("{stem}.{}", child.name())
    }
    fn leaf(
        &mut self,
        field: &FieldContract,
        stem: &str,
        _mode: super::native::Mode,
    ) -> Result<Option<String>, SchemaError> {
        Ok((field.extension().is_some()
            || pse_columnar::native_field::children(field.field().data_type()).is_empty())
        .then(|| field_row(field, stem)))
    }
    fn container(
        &mut self,
        field: &FieldContract,
        stem: &str,
        children: Vec<String>,
    ) -> Result<String, SchemaError> {
        let mut row = field_row(field, stem);
        for child in children {
            row.push_str(&child);
        }
        Ok(row)
    }
    fn nullable(&mut self, value: String, _nullable: bool) -> String {
        value
    }
}

fn field_row(field: &FieldContract, path: &str) -> String {
    use arrow_schema::DataType as D;
    let mut source = String::new();
    let ty = field.extension().map_or_else(
        || match field.data_type() {
            D::Struct(_) => "Struct".to_owned(),
            D::List(_) => "List".to_owned(),
            D::LargeList(_) => "LargeList".to_owned(),
            D::ListView(_) => "ListView".to_owned(),
            D::LargeListView(_) => "LargeListView".to_owned(),
            D::FixedSizeList(_, width) => format!("FixedSizeList({width})"),
            D::Map(_, sorted) => format!("Map(sorted={sorted})"),
            D::Union(_, mode) => format!("Union({mode:?})"),
            D::RunEndEncoded(..) => "RunEndEncoded".to_owned(),
            other => other.to_string(),
        },
        |use_| use_.name(),
    );
    let fk = field
        .fk()
        .map_or_else(|| "—".to_owned(), |fk| format!("`{fk}`"));
    let quantity = match field.quantity() {
        QuantityContract::None => "—".to_owned(),
        QuantityContract::Column(name) => format!("`{name}`"),
    };
    let _ = writeln!(
        source,
        "| `{path}` | `{ty}` | {} | `{}` | {fk} | {quantity} |",
        field.nullable(),
        field.role().as_str()
    );
    source
}

pub(super) fn generate(reg: &Registry) -> Result<GeneratedTree, SchemaError> {
    let mut tree = GeneratedTree::empty(Language::Markdown.roots());
    let mut namespaces = BTreeMap::<&str, String>::new();
    for relation in reg.relations() {
        let source = namespaces
            .entry(relation.key.namespace.as_str())
            .or_default();
        let _ = writeln!(
            source,
            "## `{}`\n\n{}\n\nVersion: {}. Snapshot class: `{}`. Primary key: `{}`.\n\n| Field path | Type | Nullable | Role | Reference | Quantity |\n|---|---|---|---|---|---|",
            relation.key.name,
            relation.doc,
            relation.key.version,
            relation.snapshot_class.as_str(),
            relation.primary_key.join(", ")
        );
        for column in &relation.columns {
            source.push_str(&super::native::render(
                &mut MarkdownPolicy,
                column,
                column.name(),
                super::native::Mode::Domain,
            )?);
        }
        source.push('\n');
        for (name, sql) in &relation.checks {
            let _ = writeln!(
                source,
                "Native row check `{name}` (must be true):\n\n```sql\n{sql}\n```\n"
            );
        }
    }
    let mut index = format!(
        "# Generated registry reference\n\nProjected from the admitted registry `{}`. This identity is not evidence of runtime validity.\n\n",
        reg.fingerprint()
    );
    for (namespace, source) in namespaces {
        let _ = writeln!(index, "- [{namespace} relations](relations/{namespace}.md)");
        emit(
            &mut tree,
            &format!("relations/{namespace}"),
            format!("# {namespace} relations\n\n{source}"),
        );
    }
    index.push_str("- [Enumerations](enums.md)\n- [Extension types](extension_types.md)\n- [Native algorithm signatures](algorithms.md)\n- [Rules and invariants](rules.md)\n");
    emit(&mut tree, "README", index);
    emit(&mut tree, "enums", enums(reg));
    let extensions = EXTENSION_TYPES
        .iter()
        .map(|extension| {
            Ok(format!(
                "## `{}`\n\n{}\n\nStorage: `{}`. Metadata version: {}.\n\n",
                extension.name,
                extension.doc,
                crate::model::render_data_type(&extension.storage())?,
                extension.metadata_version
            ))
        })
        .collect::<Result<String, SchemaError>>()?;
    emit(
        &mut tree,
        "extension_types",
        format!("# Extension types\n\n{extensions}"),
    );
    emit(&mut tree, "algorithms", algorithms(reg));
    emit(&mut tree, "rules", rules(reg));
    tree.files.insert(
        "docs/generated/schema/authoring.schema.json".into(),
        super::jsonschema::generate(reg)?.into_bytes(),
    );
    Ok(tree)
}

fn enums(reg: &Registry) -> String {
    let mut source = String::from(
        "# Enumerations\n\nMember names are canonical string values; declaration order is presentation only.\n\n",
    );
    for spec in reg.enums() {
        let _ = writeln!(source, "## `{}`\n", spec.name);
        if let Some(module) = spec.idaes_source {
            let _ = writeln!(source, "IDAES compatibility source: `{module}`.\n");
        }
        source.push_str("| Member | IDAES name | Deprecated |\n|---|---|---|\n");
        for member in &spec.members {
            let _ = writeln!(
                source,
                "| `{}` | `{}` | {} |",
                member.name,
                member.idaes_name.unwrap_or(""),
                member.deprecated
            );
        }
        source.push('\n');
    }
    source
}

fn algorithms(reg: &Registry) -> String {
    let mut source = String::from(
        "# Native algorithm signatures\n\nArguments bind actual native logical children. Dependencies and execution belong to DataFusion plans.\n\n",
    );
    for pass in reg.algorithms() {
        let _ = writeln!(
            source,
            "## {}\n\nVersion: `{}`. Determinism: `{}`. Native effects: {:?}.\n\n| Direction | Port | Relation |\n|---|---|---|",
            pass.name, pass.version, pass.determinism, pass.effects
        );
        for input in &pass.inputs {
            let _ = writeln!(
                source,
                "| input | `{}` | `{}` |",
                input.port, input.relation
            );
        }
        for output in &pass.outputs {
            let _ = writeln!(
                source,
                "| output | `{}` | `{}` |",
                output.port, output.relation
            );
        }
        source.push('\n');
    }
    source
}

fn rules(reg: &Registry) -> String {
    let mut source = String::from("# Relational invariants\n\n");
    source.push_str("## Invariants\n\n| Relation | Invariant | Native SQL |\n|---|---|---|\n");
    for invariant in reg.invariants() {
        let _ = writeln!(
            source,
            "| `{}` | `{}` | `{}` |",
            invariant.relation,
            invariant.name,
            invariant
                .query
                .replace('\n', " ")
                .replace('|', "&#124;")
                .replace('`', "&#96;")
        );
    }
    source
}
