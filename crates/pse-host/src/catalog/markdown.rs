//! Markdown publication derives from the actual parser; reads prepare no tools.
use std::io;

/// Render all non-hidden commands under an explicitly selected parser path.
pub fn render(path: &[String]) -> io::Result<String> {
    let mut command = super::command_tree();
    command.build();
    let mut name = "pse".to_owned();
    for component in path {
        command = command.find_subcommand(component).cloned().ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidInput,
                format!("unknown command path {component}"),
            )
        })?;
        name.push(' ');
        name.push_str(component);
    }
    let mut output = String::from(
        "<!-- @generated by pse-schema; do not edit -->\n\n# Agent CLI reference\n\nGenerated from the owning Clap parser. Help and discovery never prepare a tool.\n\n",
    );
    visit(command, name, &mut output);
    while output.ends_with("\n\n") {
        output.pop();
    }
    Ok(output)
}
fn visit(mut command: clap::Command, name: String, output: &mut String) {
    if command.is_hide_set() {
        return;
    }
    output.push_str("## `");
    output.push_str(&name);
    output.push_str("`\n\n~~~~text\n");
    for line in command.render_long_help().to_string().lines() {
        output.push_str(line.trim_end());
        output.push('\n');
    }
    output.push_str("\n~~~~\n\n");
    for child in command.get_subcommands() {
        visit(
            child.clone(),
            format!("{name} {}", child.get_name()),
            output,
        );
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn reference_uses_real_parser_and_excludes_hidden_controls() {
        let reference = render(&[]).unwrap();
        for name in [
            "pse",
            "pse search syntax",
            "pse inspect declaration",
            "pse propose",
            "pse observe follow",
            "pse api",
            "pse probe run",
        ] {
            assert!(reference.contains(&format!("## `{name}`")), "{name}");
        }
        assert!(!reference.contains("## `pse __supervise`"));
        assert!(!reference.contains("## `pse code query`"));
        assert!(!reference.contains("## `pse code preview`"));
        assert!(reference.contains("--tree-sitter"));
        let scoped = render(&["search".into()]).unwrap();
        assert!(scoped.contains("## `pse search syntax`"));
        assert!(!scoped.contains("## `pse observe"));
        assert!(render(&["nonexistent".into()]).is_err());
    }
}
