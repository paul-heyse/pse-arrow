use super::boundary_source::RecordLayout;

#[expect(
    clippy::too_many_arguments,
    reason = "the actual modeling declaration includes its explicit interpretation version"
)]
pub(super) fn declare(
    source: &'static str,
    builder: &mut crate::RegistryBuilder,
    namespace: crate::model::Namespace,
    name: &'static str,
    version: u32,
    class: crate::model::SnapshotClass,
    keys: &[&'static str],
    columns: Vec<crate::model::FieldContract>,
    doc: &'static str,
) {
    builder.declare_relation_result(super::boundary_source::present(
        super::declarations::declaration(namespace, name, version, class, keys, columns, doc),
        source,
        "AuthoredModelingDeclarationsRow",
        LAYOUTS,
    ));
}

