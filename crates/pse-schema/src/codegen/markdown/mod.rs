//! Readable projections of the registry; the declaration remains the authority.

use std::fmt::Write as _;

use std::collections::BTreeMap;

use crate::model::{EXTENSION_TYPES, PortSource};
use crate::{Registry, SchemaError};

use super::{GeneratedTree, Language};

const HEADER: &str = "<!-- @generated by pse-schema; do not edit -->\n\n";

fn emit(tree: &mut GeneratedTree, name: &str, mut source: String) {
    source.truncate(source.trim_end().len());
    source.push('\n');
    source.insert_str(0, HEADER);
    tree.files.insert(
        format!("docs/generated/{name}.md").into(),
        source.into_bytes(),
    );
}

pub(super) fn generate(reg: &Registry) -> Result<GeneratedTree, SchemaError> {
    let mut tree = GeneratedTree::empty(Language::Markdown.roots());
    let mut namespaces = BTreeMap::<&str, String>::new();
    for relation in reg.relations() {
        let source = namespaces
            .entry(relation.key.namespace.as_str())
            .or_default();
        let _ = writeln!(
            source,
            "## `{}`\n\n{}\n\nVersion: {}. Snapshot class: `{}`. Primary key: `{}`.\n\n| Column | Type | Nullable | Role | Reference |\n|---|---|---|---|---|",
            relation.key.name,
            relation.doc,
            relation.key.version,
            relation.snapshot_class.as_str(),
            relation.primary_key.join(", ")
        );
        for column in &relation.columns {
            let _ = writeln!(
                source,
                "| `{}` | `{}` | {} | `{}` | {} |",
                column.name,
                column.logical_type.name(),
                column.nullable,
                column.role.as_str(),
                column
                    .fk
                    .map_or_else(|| "—".to_owned(), |fk| format!("`{fk}`"))
            );
        }
        source.push('\n');
    }
    let mut index = format!(
        "# Generated registry reference\n\nProjected from the admitted registry `{}`. This identity is not evidence of runtime validity.\n\n",
        reg.fingerprint()
    );
    for (namespace, source) in namespaces {
        let _ = writeln!(index, "- [{namespace} relations](relations/{namespace}.md)");
        emit(
            &mut tree,
            &format!("relations/{namespace}"),
            format!("# {namespace} relations\n\n{source}"),
        );
    }
    index.push_str("- [Enumerations](enums.md)\n- [Extension types](extension_types.md)\n- [Executable pass contracts](passes.md)\n- [Rules and invariants](rules.md)\n");
    emit(&mut tree, "README", index);
    emit(&mut tree, "enums", enums(reg));
    let extensions = EXTENSION_TYPES
        .iter()
        .map(|extension| {
            Ok(format!(
                "## `{}`\n\n{}\n\nStorage: `{}`. Metadata version: {}.\n\n",
                extension.name,
                extension.doc,
                crate::model::render_data_type(&extension.storage())?,
                extension.metadata_version
            ))
        })
        .collect::<Result<String, SchemaError>>()?;
    emit(
        &mut tree,
        "extension_types",
        format!("# Extension types\n\n{extensions}"),
    );
    emit(&mut tree, "passes", passes(reg));
    emit(&mut tree, "rules", rules(reg));
    tree.files.insert(
        "docs/generated/schema/authoring.schema.json".into(),
        super::jsonschema::generate(reg)?.into_bytes(),
    );
    Ok(tree)
}

fn enums(reg: &Registry) -> String {
    let mut source = String::from("# Enumerations\n\nDictionary codes are presentation only.\n\n");
    for spec in reg.enums() {
        let _ = writeln!(source, "## `{}`\n", spec.name);
        if let Some(module) = spec.idaes_source {
            let _ = writeln!(source, "IDAES compatibility source: `{module}`.\n");
        }
        source.push_str("| Member | IDAES name | Deprecated |\n|---|---|---|\n");
        for member in &spec.members {
            let _ = writeln!(
                source,
                "| `{}` | `{}` | {} |",
                member.name,
                member.idaes_name.unwrap_or(""),
                member.deprecated
            );
        }
        source.push('\n');
    }
    source
}

fn passes(reg: &Registry) -> String {
    let mut source = String::from(
        "# Executable pass contracts\n\nThis is the registered executable surface. The later-pass design inventory remains in blueprint §14.1 (ADR-0056).\n\n```mermaid\ngraph TD\n",
    );
    for pass in reg.passes() {
        let _ = writeln!(source, "  {}[{}]", pass.name, pass.name);
        for input in &pass.inputs {
            if let PortSource::Derived { pass: producer, .. } = input.source {
                let _ = writeln!(source, "  {producer} --> {}", pass.name);
            }
        }
    }
    source.push_str("```\n\n");
    for pass in reg.passes() {
        let _ = writeln!(
            source,
            "## {}\n\nVersion: `{}`. Determinism: `{}`. Executes plans: {}.\n\n| Direction | Port | Relation |\n|---|---|---|",
            pass.name, pass.version, pass.determinism, pass.executes_plans
        );
        for input in &pass.inputs {
            let _ = writeln!(
                source,
                "| input | `{}` | `{}` |",
                input.port, input.relation
            );
        }
        for output in &pass.outputs {
            let _ = writeln!(
                source,
                "| output | `{}` | `{}` |",
                output.port, output.relation
            );
        }
        source.push('\n');
    }
    source
}

fn rules(reg: &Registry) -> String {
    let mut source = String::from("# Rules and invariants\n\n");
    for rule in reg.rules() {
        let _ = writeln!(
            source,
            "## `{}`\n\nVersion: `{}`. Stratum: {}.\n",
            rule.name, rule.version, rule.stratum
        );
        for dependency in reg
            .rule_dependencies()
            .iter()
            .filter(|dependency| dependency.rule_id == rule.id)
        {
            let _ = writeln!(source, "- `{}` ({})", dependency.relation, dependency.mode);
        }
        source.push('\n');
    }
    source.push_str("## Invariants\n\n| Relation | Invariant | Rule |\n|---|---|---|\n");
    for invariant in reg.invariants() {
        let _ = writeln!(
            source,
            "| `{}` | `{}` | `{}` |",
            invariant.relation, invariant.name, invariant.rule
        );
    }
    source
}
