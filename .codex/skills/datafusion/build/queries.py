"""Generate ast-grep rules from the model, and their tests.

Some questions are better answered by a rule derived from the data than by a rule written by
hand. The deprecation rule is the clearest case: the pinned release deprecates 116 items, each
with its own replacement text, and that list changes every release. Writing it by hand guarantees
it goes stale; deriving it means a rebuild keeps it exact.

Generated rules are written to `rules/generated/` and are never hand-edited. Every one of them
gets a test case built from the same data, because a rule with no invalid fixture can silently
stop matching.
"""

from __future__ import annotations

import json
from pathlib import Path

GENERATED_DIR = "rules/generated"
HEADER = "# Generated by build/queries.py from the pinned model. Do not edit by hand.\n"


def _yaml_block(text: str, indent: str = "  ") -> str:
    """Render a literal block scalar, which needs no escaping of the payload."""
    lines = [line.rstrip() for line in text.strip().splitlines()]
    return "\n".join(f"{indent}{line}" if line else "" for line in lines)


def _escape_regex(literal: str) -> str:
    out = []
    for character in literal:
        if character in r".^$*+?()[]{}|\\":
            out.append("\\" + character)
        else:
            out.append(character)
    return "".join(out)


def deprecated_rule(
    items: list[dict], ambiguous: set[str], crate_roots: list[str]
) -> tuple[str, str]:
    """One rule matching a qualified use of an item deprecated in the pinned release.

    Deliberately precise rather than exhaustive, because a hint rule that cries wolf gets ignored.
    Three constraints: the name must not be shared with anything undeprecated, the use must be a
    qualified path rather than a bare identifier, and that path must be rooted in a pinned crate.
    Dropping any one of them wrecks precision -- unanchored identifier matching produced 47 hits
    on this workspace and all 47 were collisions with local variables, module names, or
    `tokio::sync::oneshot::channel`.
    """
    names = sorted({item["name"] for item in items} - ambiguous)
    alternation = "|".join(_escape_regex(name) for name in names)
    roots = "|".join(sorted(crate_roots))

    kept = [item for item in items if item["name"] in set(names)]
    replacements = []
    for item in sorted(kept, key=lambda entry: entry["name"]):
        note = (item.get("deprecated") or "").replace("\n", " ").strip()
        replacements.append(f"  {item['name']} -- {note}")
    listing = "\n".join(replacements[:40])
    if len(replacements) > 40:
        listing += f"\n  ... and {len(replacements) - 40} more; see content/index/symbols.tsv"

    rule = f"""{HEADER}id: project-deprecated-api
language: rust
severity: hint
message: Deprecated in the pinned DataFusion release. A replacement exists.
note: |
  Deprecated code still compiles, so nothing forces a correction and a model trained before the
  deprecation keeps emitting it. These {len(names)} identifiers are deprecated as of the pinned
  release, with the replacement the upstream note names:

{_yaml_block(listing, "  ")}

  Matched only as a qualified path rooted in a pinned crate, and only for names nothing
  undeprecated shares, because ast-grep resolves no imports. A use written as
  `use arrow::x::name; name()` is therefore missed -- precision was chosen over recall here.
  Confirm against content/index/symbols.tsv before acting.
metadata:
  record: capability-gap
  capability: deprecation
  generated: true
rule:
  any:
    - kind: scoped_identifier
      regex: '^({roots})\\w*::.*({alternation})$'
    - kind: scoped_type_identifier
      regex: '^({roots})\\w*::.*({alternation})$'
"""

    sample = sorted(names)[0]
    root = sorted(crate_roots)[0]
    test = f"""{HEADER}id: project-deprecated-api
valid:
  - |
    let value = {sample}(input);
  - |
    let value = tokio::sync::oneshot::{sample}();
invalid:
  - |
    let value = {root}::some_module::{sample}(input);
"""
    return rule, test


def generate(model_root: Path, queries_root: Path, crate_roots: list[str]) -> dict[str, int]:
    """Write every generated rule. Returns a count per rule id."""
    deprecated: list[dict] = []
    live_names: set[str] = set()
    for document in sorted(model_root.glob("*.json")):
        payload = json.loads(document.read_text())
        for item in payload.get("items", []):
            if item.get("deprecated"):
                deprecated.append(item)
            else:
                live_names.add(item["name"])

    target = queries_root / GENERATED_DIR
    target.mkdir(parents=True, exist_ok=True)
    tests = queries_root / "rule-tests"
    tests.mkdir(parents=True, exist_ok=True)

    written: dict[str, int] = {}
    if deprecated:
        rule, test = deprecated_rule(deprecated, live_names, crate_roots)
        (target / "project-deprecated-api.yml").write_text(rule)
        (tests / "project-deprecated-api-test.yml").write_text(test)
        written["project-deprecated-api"] = len({i["name"] for i in deprecated} - live_names)
    return written
