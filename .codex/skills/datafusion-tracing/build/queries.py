"""Generate the one rule that must be derived from the model rather than written by hand.

A hand-written list of names goes stale silently: the rule keeps passing its fixtures while the
library it describes moves underneath it. `project-doc-hidden-api` is regenerated from the built
model on every build, so it cannot.

ast-grep resolves no imports, so the rule matches only qualified paths rooted in a pinned crate.
`use datafusion_tracing::new_instrument_rule; new_instrument_rule(..)` is missed. Precision was
chosen over recall deliberately -- an unanchored identifier rule for a name as generic as
`new_instrument_rule` matches any function of that name in any crate.
"""

from __future__ import annotations

import json
from pathlib import Path

HEADER = "# Generated by build/queries.py from the pinned model. Do not edit by hand.\n"

RULE = """{header}id: project-doc-hidden-api
language: rust
severity: hint
message: a #[doc(hidden)] item used directly; the macro is the supported route
note: |
  Upstream's comment beside these re-exports reads: "These functions are only public because
  they need to be accessed by the macros, but they're not intended for direct use by consumers
  of this crate."

  Calling one compiles and works. It also opts you out of every compatibility promise the
  macros carry, and `#[doc(hidden)]` items are the ones upstream may change without a note in
  the changelog. Use `instrument_with_*_spans!` or `instrument_rules_with_*_spans!` instead.

  {count} identifier(s), regenerated from the model on every build.

  PRECISION: ast-grep resolves no imports, so only a path qualified with a pinned crate root
  matches. A bare call after `use` is missed, because an unanchored rule for a name this
  generic would match any function called that in any crate.
metadata:
  record: doc-hidden-use
  capability: exec-instrumentation
rule:
  any:
    - kind: scoped_identifier
      regex: '^({roots})\\s*::.*\\b({names})$'
    - kind: scoped_type_identifier
      regex: '^({roots})\\s*::.*\\b({names})$'
"""

TEST = """{header}id: project-doc-hidden-api
valid:
  - 'let rule = instrument_with_info_spans!(options: options);'
  - 'let x = other_crate::{first}(a);'
invalid:
{invalid}"""


def generate(model_root: Path, queries_root: Path, items: dict, classifications: dict) -> dict:
    """Write `rules/generated/project-doc-hidden-api.yml` and its fixture."""
    names = sorted(
        {
            item.name
            for item in items.values()
            if item.visibility == "doc-hidden" and item.name
        }
        | {
            name
            for classification in classifications.values()
            for name in classification.absent_from_rustdoc
        }
    )
    roots = sorted(
        {item.crate.replace("-", "_") for item in items.values() if item.visibility == "doc-hidden"}
    ) or ["datafusion_tracing"]

    if not names:
        raise RuntimeError(
            "no doc(hidden) names were found. The rule would match nothing and its fixtures "
            "would still pass, which is how a generated rule goes stale without failing."
        )

    generated = queries_root / "rules" / "generated"
    tests = queries_root / "rule-tests"
    generated.mkdir(parents=True, exist_ok=True)
    tests.mkdir(parents=True, exist_ok=True)

    (generated / "project-doc-hidden-api.yml").write_text(
        RULE.format(
            header=HEADER,
            count=len(names),
            roots="|".join(roots),
            names="|".join(names),
        )
    )
    invalid = "\n".join(
        f"  - 'let x = {roots[0]}::{name}(a);'" for name in names
    )
    (tests / "project-doc-hidden-api-test.yml").write_text(
        TEST.format(header=HEADER, first=names[0], invalid=invalid + "\n")
    )
    return {"project-doc-hidden-api": len(names)}
