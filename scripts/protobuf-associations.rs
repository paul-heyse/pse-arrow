//! Producer-specific explicit protobuf-to-generated-Rust associations, never semantic identity.
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Qualified native syntax grammar for generator-owned authored byte correspondence.
pub(super) const SOURCE_RANGE_PRODUCER: &str = "tree-sitter-proto/0.6.0";
/// Exact descriptor-qualified syntax profile; never a descriptor-column conversion.
pub(super) const SOURCE_RANGE_PROFILE: &str =
    "descriptor-qualified-message-and-field/utf8-bytes-v1";

/// Generator-qualified original byte interval, bound by the enclosing source/descriptor hashes.
#[derive(Clone, Debug, Eq, PartialEq, Deserialize, Serialize, JsonSchema)]
pub struct SourceByteRange {
    /// Inclusive original UTF-8 byte offset.
    pub start: usize,
    /// Exclusive original UTF-8 byte offset.
    pub end: usize,
    /// Explicitly qualified native syntax grammar version.
    pub producer: String,
    /// Qualified source correspondence profile; unknown profiles remain unsupported.
    pub profile: String,
}

/// Exact declaration association nominated by generated trait/accessor evidence.
#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
pub struct Association {
    /// Full message name, or full message name followed by #field-number.
    pub declaration: String,
    /// Authored proto file relative to the checkout.
    pub source: String,
    /// Original authored bytes.
    pub source_sha256: String,
    /// Exact generator-qualified authored bytes; absence establishes no byte correspondence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_range: Option<SourceByteRange>,
    /// Why an authored interval was not qualified, independent from declaration association.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_range_unavailable: Option<String>,
    /// Generated Rust file relative to the checkout.
    pub output: String,
    /// Original generated bytes.
    pub output_sha256: String,
    /// Type spelled by the explicit generated implementation.
    pub rust_type: String,
    /// Member spelled by the explicit numbered accessor, when unambiguous.
    pub rust_field: Option<String>,
    /// Read-time qualification, empty in the immutable producer declaration.
    #[serde(default)]
    pub state: String,
}
/// One generator's descriptor/configuration-qualified associations.
#[derive(Debug, Deserialize, Serialize)]
pub struct AssociationManifest {
    /// Exact full descriptor artifact identity.
    pub descriptor_sha256: String,
    /// Source/configuration/emitter bytes required for this generation.
    pub inputs: BTreeMap<String, String>,
    /// Explicit associations only; unsupported shapes remain absent.
    pub associations: Vec<Association>,
}
