"""Derive Cyclopts argv declarations from the canonical unfiltered tool schemas.

The narrow mapping follows FastMCP4.1.3's schema-to-Cyclopts approach. Presence,
selection and complete results deliberately belong to the independent shared runtime.
"""

from __future__ import annotations

import argparse
import keyword
import re
from pathlib import Path
from typing import TYPE_CHECKING

from scripts.capabilities.execution_basis import digest

if TYPE_CHECKING:
    from collections.abc import Mapping

    from fastmcp.tools import Tool
    from pydantic import JsonValue

    from scripts.capabilities.model import Capability
    from scripts.capabilities.server import Runtime

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "scripts/generated/capabilities"
MARKER = "# @generated by scripts.capabilities.cli_codegen; do not edit"


def render(runtime: Runtime) -> str:
    return render_tools(
        runtime.catalogue.tools, runtime.catalogue.capabilities, runtime.interface.wires
    )


def render_tools(
    tools: Mapping[str, Tool],
    capabilities: Mapping[str, Capability],
    wires: Mapping[str, dict[str, JsonValue]],
) -> str:
    operations = {}
    definitions = []
    for index, (identity, tool) in enumerate(sorted(tools.items())):
        spec = capabilities[identity]
        operations[identity] = {
            "wire_revision": digest(wires[identity]),
            "lifetime": spec.invocation_lifetime,
            "read_only": tool.annotations.read_only_hint if tool.annotations else None,
        }
        parameters = tool.parameters
        properties = parameters.get("properties", {})
        required = parameters.get("required", [])
        args = []
        values = []
        for position, (name, schema) in enumerate(properties.items()):
            variable = "arg_" + str(position) + "_" + re.sub(r"\W", "_", name)
            if keyword.iskeyword(variable):
                variable += "_"
            simple = schema.get("type") in (
                "string",
                "boolean",
                "integer",
                "number",
            ) and not any(key in schema for key in ("anyOf", "oneOf", "$ref"))
            annotation = (
                {
                    "string": "str",
                    "boolean": "bool",
                    "integer": "int",
                    "number": "float",
                }.get(schema.get("type"), "str")
                if simple
                else "str"
            )
            optional = name not in required
            help_text = str(schema.get("description", "")) + (
                " JSON value." if not simple else ""
            )
            args.append(
                f"        {variable}: Annotated[{annotation + ' | None' if optional else annotation}, Parameter(name={('--' + name.replace('_', '-'))!r}, help={help_text!r})]"
                + (" = None" if optional else "")
                + ","
            )
            expression = variable if simple else f"parse_value({variable})"
            values.append(
                ("        if " + variable + " is not None:\n    " if optional else "")
                + f"        arguments[{name!r}] = {expression}"
            )
        signature = "*,\n" + "\n".join(args) if args else ""
        definitions.append(
            f"    @app.command(name={identity!r}, help={tool.description!r})\n    def operation_{index}({signature}) -> None:\n        arguments: dict[str, JsonValue] = {{}}\n"
            + "\n".join(values)
            + f"\n        call({identity!r}, arguments, OPERATIONS[{identity!r}])\n"
        )
    return "\n".join(
        [
            MARKER,
            "# SPDX-" + "License-Identifier: MIT OR Apache-2.0",
            "# Copyright (c) 2026 Paul Heyse",
            "from typing import TYPE_CHECKING, Annotated",
            "",
            "from cyclopts import App, Parameter",
            "from scripts.capability_cli_runtime import call, parse_value",
            "",
            "if TYPE_CHECKING:",
            "    from pydantic import JsonValue",
            "",
            "",
            "OPERATIONS = " + repr(operations),
            "def register() -> App:",
            "    app = App(name='call', help='Exact canonical operations; complex fields accept JSON values.')",
            *definitions,
            "    return app",
            "",
        ]
    )


def check(content: str, directory: Path) -> tuple[str, ...]:
    for ancestor in (directory.absolute(), *directory.absolute().parents):
        if ancestor.is_symlink():
            return ("symlink generated CLI path",)
    if not directory.exists():
        return ("missing generated CLI",)
    if not directory.is_dir():
        return ("invalid generated CLI directory",)
    result = []
    for path in directory.iterdir():
        if (
            path.name == "__pycache__"
            and path.is_dir()
            and not path.is_symlink()
            and all(
                child.is_file()
                and not child.is_symlink()
                and re.fullmatch(
                    r"cli\.cpython-[0-9]+(?:\.opt-[0-9]+)?\.pyc", child.name
                )
                for child in path.iterdir()
            )
        ):
            continue
        if path.is_symlink() or not path.is_file() or path.name != "cli.py":
            result.append("unexpected generated CLI entry: " + path.name)
    target = directory / "cli.py"
    if (
        not target.is_file()
        or target.is_symlink()
        or target.read_text(encoding="utf-8") != content
    ):
        result.append("missing/stale generated CLI: cli.py")
    return tuple(result)


def publish(content: str, directory: Path) -> None:
    issues = check(content, directory)
    if any(
        "symlink" in item or "invalid" in item or "unexpected" in item
        for item in issues
    ):
        raise ValueError("; ".join(issues))
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "cli.py").write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output-dir", type=Path, default=OUTPUT)
    args = parser.parse_args()
    # Only publication prepares the serving catalogue.
    from scripts.capabilities.server import build  # noqa: PLC0415

    content = render(build())
    if args.check:
        issues = check(content, args.output_dir)
        for issue in issues:
            print(issue)
        return int(bool(issues))
    publish(content, args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
