"""Derive the complete reference from the composed, source-only endpoint.

The provider contract exposes composed definitions before session visibility filtering.
No tool, resource reader, prompt renderer, lifespan or native receiver is invoked.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import stat
from pathlib import Path
from typing import TYPE_CHECKING

from fastmcp.server.providers import Provider

from scripts.capabilities.catalogue import JSON_OBJECT

if TYPE_CHECKING:
    from fastmcp.tools import Tool
    from pydantic import BaseModel, JsonValue

    from scripts.capabilities.server import Runtime

ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIRECTORY = Path("docs/generated/capabilities")
FILENAME = "reference.md"
LEGACY_OUTPUT = Path("docs/generated/capabilities.md")
MARKER = "<!-- @generated by scripts.capabilities.reference; do not edit -->"


def _json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False)


def _block(value: object) -> str:
    # A longer fence also retains literal Markdown fences in descriptions/defaults.
    body = _json(value)
    longest = max(
        (len(part) for part in body.split("\n") if part and set(part) == {"`"}),
        default=0,
    )
    fence = "`" * max(3, longest + 1)
    return f"{fence}json\n{body}\n{fence}\n"


def _wire(component: BaseModel) -> dict[str, JsonValue]:
    return JSON_OBJECT.validate_python(
        component.model_dump(mode="json", by_alias=True, exclude_none=True)
    )


def _source(path: str) -> str:
    """Link checkout owners from the dedicated generated capabilities directory."""
    return f"[{path}](../../../{path})"


def _tool(tool: Tool) -> list[str]:
    return [
        f"### `{tool.name}`\n",
        f"Exact component key: `{tool.key}`.\n",
        _block(_wire(tool.to_mcp_tool())),
    ]


def _native_links(metadata: dict[str, JsonValue]) -> list[str]:
    """Render links carried by actual native binding metadata, without a schema DTO."""
    native = metadata.get("pse.native")
    if not isinstance(native, dict):
        return []
    contracts = native.get("contracts")
    lines = []
    if isinstance(contracts, dict):
        for field, contract in sorted(contracts.items()):
            if isinstance(contract, dict) and isinstance(contract.get("schema_path"), str):
                lines.append(f"- Native `{field}`: {_source(str(contract['schema_path']))}.\n")
    authoring = native.get("authoring_guidance")
    if isinstance(authoring, dict) and isinstance(authoring.get("path"), str):
        lines.append(f"- Authoring guidance: {_source(str(authoring['path']))}.\n")
    return lines


async def render_async(runtime: Runtime) -> str:
    """Render definitions independently of attachment selection and live readiness."""
    # Provider's public list methods include composition and transforms, retaining
    # disabled definitions. FastMCP's overrides additionally filter attachments,
    # authorization and middleware; those are deliberately not inventory sources.
    server = runtime.server
    tools, resources, templates, prompts = await asyncio.gather(
        Provider.list_tools(server),
        Provider.list_resources(server),
        Provider.list_resource_templates(server),
        Provider.list_prompts(server),
    )
    catalogue = runtime.catalogue
    canonical = catalogue.tools
    registered = {tool.key: tool for tool in tools}
    missing = {tool.key for tool in canonical.values()} - set(registered)
    if missing:
        raise ValueError("canonical tools are not registered: " + ", ".join(sorted(missing)))
    lines = [
        MARKER + "\n",
        "# Canonical capability reference\n",
        "Derived from the complete composed endpoint, before attachment visibility. "
        "Hidden operations remain included. Declarations and schemas establish the interface; "
        "they do not establish service readiness or exercised scientific behavior.\n",
        "Regenerate with `just codegen`; compare without writes with `just codegen-check`. "
        "Authored workflow rationale remains with the linked source owners.\n",
        f"Catalogue content revision: `{catalogue.revision}`.\n",
        "## Domains\n",
    ]
    for identity, domain in sorted(catalogue.domains.items()):
        lines.extend([f"### `{identity}` — {domain.title}\n", _block(domain.model_dump(mode="json"))])
    lines.append("## Workflows\n")
    for identity, workflow in sorted(catalogue.workflows.items()):
        lines.extend([f"### `{identity}` — {workflow.title}\n", _block(workflow.model_dump(mode="json"))])
    lines.append("## Guidance owners\n")
    for identity, guide in sorted(catalogue.guides.items()):
        lines.append(f"- `{identity}` — {guide.title}: {_source(guide.path)}; resource `{guide.uri}`.\n")
    lines.append("\n## Bootstrap and composition controls\n")
    for _key, tool in sorted(registered.items()):
        if tool.name not in canonical:
            lines.extend(_tool(tool))
    lines.append("## Canonical capabilities\n")
    for identity, spec in sorted(catalogue.capabilities.items()):
        lines.extend([
            f"### `{identity}` — {spec.title}\n",
            f"Exposure: **{spec.exposure}**. Owner: `{spec.owner}`. "
            f"Declaration source: {_source(spec.source)}.\n",
            _block(spec.model_dump(mode="json")),
        ])
        tool = canonical.get(identity)
        if tool is not None:
            lines.extend([
                f"Exact callable component key: `{tool.key}`. "
                "The following is the registered MCP definition, including input/output "
                "schemas, required fields, defaults, annotations and native contract identities.\n",
                _block(_wire(tool.to_mcp_tool())),
            ])
            lines.extend(_native_links(JSON_OBJECT.validate_python(tool.meta or {})))
    lines.append("## Registered resources\n")
    for resource in sorted(resources, key=lambda item: item.key):
        lines.extend([
            f"### `{resource.key}`\n",
            _block(_wire(resource.to_mcp_resource())),
        ])
    lines.append("## Registered resource templates\n")
    for template in sorted(templates, key=lambda item: item.key):
        lines.extend([
            f"### `{template.key}`\n",
            _block({"definition": _wire(template.to_mcp_template()), "parameters": template.parameters}),
        ])
    lines.append("## Registered prompts\n")
    for prompt in sorted(prompts, key=lambda item: item.key):
        lines.extend([
            f"### `{prompt.key}`\n",
            _block({"definition": _wire(prompt.to_mcp_prompt()), "arguments": [argument.model_dump(mode="json") for argument in prompt.arguments or []]}),
        ])
    return "\n".join(lines).rstrip() + "\n"


def render(runtime: Runtime) -> str:
    """Synchronous generator entry; async consumers use render_async instead."""
    return asyncio.run(render_async(runtime))


def _owned(directory: Path) -> tuple[Path, ...]:
    """Find marker-owned stale output eligible for deletion, never symlinks."""
    return tuple(
        path
        for path in sorted(directory.glob("*.md"))
        if not path.is_symlink()
        and path.is_file()
        and path.read_bytes().split(b"\n", 1)[0] == MARKER.encode()
    )


def _symlink_ancestor(path: Path) -> Path | None:
    for ancestor in reversed((path.absolute(), *path.absolute().parents)):
        if ancestor.is_symlink():
            return ancestor
    return None


def _inventory(directory: Path) -> tuple[set[Path], tuple[str, ...]]:
    """Inspect the exclusive namespace without following directory or file links."""
    ancestor = _symlink_ancestor(directory)
    if ancestor is not None:
        return set(), (f"symlink generated reference path: {ancestor}",)
    if not directory.exists():
        return set(), ()
    if not directory.is_dir():
        return set(), (f"invalid generated reference directory: {directory}",)
    files: set[Path] = set()
    differences: list[str] = []
    pending = [directory]
    while pending:
        parent = pending.pop()
        for path in sorted(parent.iterdir()):
            relative = path.relative_to(directory)
            mode = path.lstat().st_mode
            if stat.S_ISLNK(mode):
                differences.append(f"symlink generated reference: {relative.as_posix()}")
            elif stat.S_ISDIR(mode):
                differences.append(f"unexpected generated reference directory: {relative.as_posix()}")
                pending.append(path)
            elif stat.S_ISREG(mode):
                files.add(relative)
            else:
                differences.append(f"invalid generated reference file: {relative.as_posix()}")
    return files, tuple(sorted(differences))


def _legacy(directory: Path) -> Path | None:
    """Recognize only the exact previous output during canonical publication."""
    if directory.resolve() != (ROOT / OUTPUT_DIRECTORY).resolve():
        return None
    path = ROOT / LEGACY_OUTPUT
    if _symlink_ancestor(path) is not None:
        return None
    if not path.is_symlink() and path.is_file() and path.read_bytes().split(b"\n", 1)[0] == MARKER.encode():
        return path
    return None


def check(content: str, directory: Path) -> tuple[str, ...]:
    """Compare exact owned inventory and bytes without publishing or deleting."""
    target = directory / FILENAME
    files, invalid = _inventory(directory)
    differences = [
        f"unexpected generated reference: {path.as_posix()}"
        for path in sorted(files)
        if path != Path(FILENAME)
    ]
    differences.extend(invalid)
    if Path(FILENAME) not in files:
        differences.append(f"missing generated reference: {FILENAME}")
    elif target.read_bytes() != content.encode("utf-8"):
        differences.append(f"stale generated reference: {FILENAME}")
    if _legacy(directory) is not None:
        differences.append(f"legacy generated reference: {LEGACY_OUTPUT.as_posix()}")
    return tuple(differences)


def publish(content: str, directory: Path) -> None:
    """Publish only this generator's output and retire its stale named outputs."""
    _files, invalid = _inventory(directory)
    unsafe = [difference for difference in invalid if not difference.startswith("unexpected generated reference directory:")]
    if unsafe:
        raise ValueError("; ".join(unsafe))
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / FILENAME
    for stale in _owned(directory):
        if stale != target:
            stale.unlink()
    if not target.is_file() or target.read_bytes() != content.encode("utf-8"):
        target.write_text(content, encoding="utf-8")
    legacy = _legacy(directory)
    if legacy is not None:
        legacy.unlink()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare only; never publish.")
    parser.add_argument("--output-dir", type=Path, default=ROOT / OUTPUT_DIRECTORY)
    args = parser.parse_args(argv)
    # Import only when generating: server composition never imports this entry point.
    from scripts.capabilities.server import build  # noqa: PLC0415 -- composition is loaded only by the generator entry point.

    content = render(build())
    if args.check:
        differences = check(content, args.output_dir)
        for difference in differences:
            print(difference)
        return int(bool(differences))
    publish(content, args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
