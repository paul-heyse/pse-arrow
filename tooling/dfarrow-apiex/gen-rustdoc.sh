#!/usr/bin/env bash
# Generate rustdoc JSON for selected packages of a pinned worktree.
#
# Packages are documented through a generated *extraction root* crate that
# path-depends on them, rather than by running `cargo doc` inside the upstream
# workspace. That isolates the run from unrelated workspace members whose
# dependencies may be unsatisfiable offline (e.g. arrow-avro -> md5), and makes
# the enabled feature set an explicit, recorded property of the extraction.
set -euo pipefail

ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)"
TOOLCHAIN="${DFARROW_TOOLCHAIN:-nightly-2026-08-18}"
TRIPLE="${DFARROW_TRIPLE:-x86_64-unknown-linux-gnu}"

usage() { echo "usage: gen-rustdoc.sh <worktree> <profile> <pkg[:feat,feat]> ..." >&2; exit 2; }
[ $# -ge 3 ] || usage

WORKTREE="$1"; PROFILE="$2"; shift 2
[ -d "$WORKTREE" ] || { echo "no such worktree: $WORKTREE" >&2; exit 2; }
# Path dependencies are resolved relative to the generated root crate, which
# lives elsewhere, so the worktree path must be absolute.
WORKTREE="$(cd "$WORKTREE" && pwd)"

ROOTDIR="$ROOT/build/doc-root/$PROFILE"
OUTDIR="$ROOT/build/rustdoc/$PROFILE"
TARGETDIR="$ROOT/build/target/$PROFILE"
mkdir -p "$ROOTDIR/src" "$OUTDIR" "$TARGETDIR"

{
  echo '# GENERATED by gen-rustdoc.sh — do not edit.'
  echo '[package]'
  echo 'name = "dfarrow-doc-root"'
  echo 'version = "0.0.0"'
  echo 'edition = "2021"'
  echo 'publish = false'
  echo
  echo '[lib]'
  echo 'path = "src/lib.rs"'
  echo
  echo '[dependencies]'
  for spec in "$@"; do
    pkg="${spec%%:*}"
    feats="${spec#*:}"
    dir="$(find "$WORKTREE" -maxdepth 3 -name Cargo.toml -exec grep -l "^name = \"$pkg\"" {} \; | head -1)"
    [ -n "$dir" ] || { echo "package not found in worktree: $pkg" >&2; exit 2; }
    dir="$(dirname "$dir")"
    if [ "$feats" = "$spec" ] || [ -z "$feats" ]; then
      echo "$pkg = { path = \"$dir\" }"
    else
      IFS=',' read -ra fs <<< "$feats"
      printf '%s = { path = "%s", features = [' "$pkg" "$dir"
      printf '"%s", ' "${fs[@]}"
      echo '] }'
    fi
  done
  echo
  echo '[workspace]'
} > "$ROOTDIR/Cargo.toml"

echo '// Generated extraction root. Documents its dependencies, nothing else.' > "$ROOTDIR/src/lib.rs"

export RUSTC_WRAPPER="${RUSTC_WRAPPER:-sccache}"
export RUSTUP_TOOLCHAIN="$TOOLCHAIN"
export RUSTDOCFLAGS="-Zunstable-options --output-format=json"

cd "$ROOTDIR"
# Resolve first so the lockfile is written, then document each package.
cargo generate-lockfile --offline >/dev/null 2>&1 || cargo generate-lockfile --offline
PKGSEL=()
for spec in "$@"; do PKGSEL+=( -p "${spec%%:*}" ); done
cargo doc --offline --locked --no-deps "${PKGSEL[@]}" --lib \
  --target "$TRIPLE" --target-dir "$TARGETDIR"

copied=0
for spec in "$@"; do
  pkg="${spec%%:*}"; mod="${pkg//-/_}"
  src="$TARGETDIR/$TRIPLE/doc/$mod.json"
  if [ -f "$src" ]; then cp "$src" "$OUTDIR/$mod.json"; copied=$((copied+1));
  else echo "MISSING rustdoc json for $pkg ($src)" >&2; fi
done
echo "profile=$PROFILE toolchain=$TOOLCHAIN copied=$copied -> $OUTDIR"
